/*
 * Stage 1 of the driver-to-task assignment engine (see project chat for the full spec).
 *
 * Different job from order_b_engine.js/joint_scheduler.js: those *generate* trips/tasks from a
 * raw Order B file. This engine assumes the tasks already exist, in two files a supervisor
 * already has:
 *   - a Roster (Control Staff) workbook: one row per driver, one column per day of the month,
 *     each day cell either blank (available), a leave/absence code (F/O/V/VR/A0/... or a
 *     training code like "830/7T"), or (once assigned) a task code.
 *   - a Task Program workbook: one sheet per day, one row per task slot, with a "Tasks" (task
 *     code) column and a "NAME" column that's blank/unresolved until a driver is assigned.
 *
 * The job here is purely the assignment + write-back loop a supervisor currently does by hand:
 * pick an available driver for each task, write their name onto the task, and write the task
 * code back onto their roster day -- nothing about *which* driver is generated by any of the
 * order_b_engine trip-matching logic, since these tasks are already fully formed.
 *
 * Both workbooks are read and written with ExcelJS so every existing style/merge/formula that
 * isn't touched survives untouched -- the two output files must look exactly like the input
 * files except for the specific cells this engine fills in.
 */
(function (root, factory) {
  if (typeof module === "object" && module.exports) {
    module.exports = factory();
  } else {
    root.DriverAssignmentEngine = factory();
  }
})(typeof self !== "undefined" ? self : this, function () {

  function dateKey(d) {
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
  }

  function addDays(date, n) {
    const d = new Date(date.getFullYear(), date.getMonth(), date.getDate());
    d.setDate(d.getDate() + n);
    return d;
  }

  // Any non-blank cell -- a leave code, a training code, or an already-assigned task code --
  // means that driver isn't free to take on new work that day.
  function isAvailable(status) {
    return status == null || String(status).trim() === "";
  }

  // The roster's identity/header columns (STAFF, ID, CATEGORY, Phone, and the date headers) are
  // themselves formulas pulling from an external "JAN" master sheet in a different workbook --
  // ExcelJS gives back {formula, result} for those instead of a plain value. Day-status cells
  // (F/V/O/a task code/...) are already plain literals, so this is a no-op for them. A cached
  // date-formula result also comes back as an ISO string rather than a real Date, so this
  // normalizes that too, since date detection elsewhere expects a Date instance.
  function displayValue(cell) {
    let v = cell.value;
    if (v && typeof v === "object" && !(v instanceof Date) && "result" in v) {
      v = v.result;
      if (v && typeof v === "object" && "error" in v) return null; // e.g. unresolved VLOOKUP -> #N/A
    }
    if (typeof v === "string" && /^\d{4}-\d{2}-\d{2}T/.test(v)) {
      const d = new Date(v);
      if (!isNaN(d.getTime())) return d;
    }
    return v;
  }

  // "R" anywhere in the letters after the duration means Reserve (however many letters follow --
  // R/RB/RK/RA/... are all still Reserve, the letter is a station/sequence detail we don't need
  // to interpret). "S" (and no "R") means Sweep, the track-inspection run. Anything else is a
  // real trip. The route-digit group is OPTIONAL -- confirmed directly against a real file: most
  // reserve codes carry one ("0700/7RA"), but a reserve slot with no real route to attach to
  // sometimes has none at all ("1100/RA") -- both are real, both mean the same thing.
  function classifyCode(code) {
    const m = /^(\d{3,4})\/(\d{0,2})([A-Za-z]{1,3})\s*$/.exec(String(code).trim());
    if (!m) return "trip";
    const suffix = m[3].toUpperCase();
    if (suffix.includes("R")) return "reserve";
    if (suffix.includes("S")) return "sweep";
    return "trip";
  }

  // The first letter of a trip code's suffix names its destination -- confirmed directly by the
  // supervisor: L = MAK (Makkah), A = KAIA (the airport), M = MAD (Madinah). Only meaningful for
  // "trip" kind codes (reserve/sweep codes use R/S for that same position to mean something
  // else entirely, handled by classifyCode above).
  function classifyDestination(code) {
    const m = /^(\d{3,4})\/(\d{0,2})([A-Za-z]{1,3})\s*$/.exec(String(code).trim());
    if (!m) return null;
    const first = m[3][0].toUpperCase();
    if (first === "L") return "MAK";
    if (first === "A") return "KAIA";
    if (first === "M") return "MAD";
    return null;
  }

  // The real roster never carries a task code's full letter suffix -- confirmed directly against
  // a real completed month by cross-referencing 48 real driver/day pairs against the Task
  // Program's own codes: a task like "0600/7RK" (reserve) always lands in the roster as just
  // "0600/7", the same "HHMM/routeDigits" shape a plain trip code like "0700/7A" also gets
  // trimmed down to. Reserve and trip end up looking identical in the roster text -- there's no
  // separate "RESERVE" label anywhere in a real file. The one exception: a code with no route
  // digits at all between the slash and the letters (e.g. "1100/RA", seen when a reserve slot
  // has no route number) is left completely untouched, since there's nothing to trim down to.
  function stripCodeForRoster(code) {
    const s = String(code).trim();
    const m = /^(\d{3,5}\/\d{1,2})[A-Za-z]{1,3}\s*$/.exec(s);
    return m ? m[1] : s;
  }

  // A task's cell being highlighted yellow in the Task Program is how the supervisor marks that
  // specific leg as a Passenger assignment (as opposed to Main/driving) -- confirmed directly.
  function isPassengerLegCell(cell) {
    const fill = cell.fill;
    if (!fill || fill.type !== "pattern" || fill.pattern !== "solid") return false;
    const argb = fill.fgColor && fill.fgColor.argb;
    return typeof argb === "string" && argb.toUpperCase().endsWith("FFFF00");
  }

  // Finds a header row by scanning for an exact (case-insensitive) label match rather than
  // assuming fixed row/column numbers -- the real files aren't guaranteed to keep the same
  // layout from month to month, only the same labels.
  function findHeaderCell(ws, label, maxScanRow) {
    const target = label.trim().toUpperCase();
    for (let r = 1; r <= maxScanRow; r++) {
      const row = ws.getRow(r);
      for (let c = 1; c <= ws.columnCount; c++) {
        const v = displayValue(row.getCell(c));
        if (typeof v === "string" && v.trim().toUpperCase() === target) {
          return { row: r, col: c };
        }
      }
    }
    return null;
  }

  // --- Roster (Control Staff) parsing ------------------------------------------------------
  function parseRoster(workbook) {
    const ws = workbook.worksheets[0];
    const staffCell = findHeaderCell(ws, "STAFF", 15);
    if (!staffCell) throw new Error("Could not find the roster's \"STAFF\" header -- is this a Control Staff roster file?");
    const idCell = findHeaderCell(ws, "ID", 15);
    const phoneCell = findHeaderCell(ws, "Phone", 15);
    const categoryCell = findHeaderCell(ws, "CATEGORY", 15);

    const headerRow = staffCell.row;
    const staffCol = staffCell.col;
    const headerRowObj = ws.getRow(headerRow);
    const dateCols = [];
    for (let c = staffCol + 1; c <= ws.columnCount; c++) {
      const v = displayValue(headerRowObj.getCell(c));
      if (v instanceof Date) dateCols.push({ col: c, date: v, key: dateKey(v) });
    }
    if (!dateCols.length) throw new Error("Could not find any date columns on the roster's header row.");

    const drivers = [];
    for (let r = headerRow + 1; r <= ws.rowCount; r++) {
      const row = ws.getRow(r);
      const staffVal = displayValue(row.getCell(staffCol));
      // Real driver rows are "<ID>-<NAME>" (trainees show as "T- <ID>-<NAME>"); the
      // footer/summary block below the driver list doesn't match this shape, which is how we
      // know to stop without hardcoding a row number.
      if (typeof staffVal !== "string" || !staffVal.includes("-")) continue;
      const idValRaw = idCell ? displayValue(row.getCell(idCell.col)) : null;
      // Strip everything but digits -- a stray invisible character or trailing space in the ID
      // cell (seen in real data) would otherwise silently drop that driver from the roster.
      const idDigits = idValRaw == null ? "" : String(idValRaw).replace(/[^\d]/g, "");
      if (!/^\d{5,8}$/.test(idDigits)) continue;

      // Locate the ID inside the STAFF text itself (rather than just splitting on the first
      // dash) so a "T- " trainee prefix doesn't get swallowed into the name -- and keep whatever
      // that prefix literally was (namePrefix), so a written-back task assignment can reproduce
      // it exactly rather than assuming every file spells it "T- ".
      const idPosInStaff = staffVal.indexOf(idDigits);
      const namePrefix = idPosInStaff >= 0 ? staffVal.slice(0, idPosInStaff) : "";
      const name = idPosInStaff >= 0
        ? staffVal.slice(idPosInStaff + idDigits.length).replace(/^[\s-]+/, "").trim()
        : staffVal.slice(staffVal.indexOf("-") + 1).trim();
      const phoneVal = phoneCell ? displayValue(row.getCell(phoneCell.col)) : null;
      const categoryVal = categoryCell ? displayValue(row.getCell(categoryCell.col)) : null;

      const statusByDateKey = {};
      const colByDateKey = {};
      dateCols.forEach(({ col, key }) => {
        statusByDateKey[key] = displayValue(row.getCell(col));
        colByDateKey[key] = col;
      });

      drivers.push({
        id: idDigits,
        name,
        namePrefix,
        phone: phoneVal != null ? String(phoneVal).trim() : "",
        category: categoryVal != null ? String(categoryVal).trim() : "",
        row: r,
        statusByDateKey,
        colByDateKey,
      });
    }
    if (!drivers.length) throw new Error("Found the roster's header row but no driver rows underneath it.");

    return { sheetName: ws.name, headerRow, staffCol, dateKeys: dateCols.map((d) => d.key), drivers };
  }

  // Time-of-day cells (Start/End) load as native Date objects anchored to an arbitrary epoch
  // (Excel's own "time-only" serial-date convention) -- only the hour/minute portion means
  // anything, and it's UTC because that's how ExcelJS parses the underlying serial number.
  function timeCellToMinutes(v) {
    return v instanceof Date ? v.getUTCHours() * 60 + v.getUTCMinutes() : null;
  }

  // Fallback for a task whose Start CELL is blank -- reads the time straight out of the code's own
  // leading digits instead (e.g. "0500/7R" -> 05:00), which a real Task Program's own codes always
  // agree with wherever a real Start cell is present too. See parseTaskProgram for why this matters.
  function deriveStartMinFromCode(code) {
    const m = /^(\d{3,4})\//.exec(code);
    if (!m) return null;
    const digits = m[1].padStart(4, "0");
    const h = parseInt(digits.slice(0, 2), 10);
    const mm = parseInt(digits.slice(2), 10);
    if (h > 23 || mm > 59) return null;
    return h * 60 + mm;
  }

  // A tab's own date CELLS are inconsistent test placeholders (confirmed with the supervisor),
  // not usable -- but every real Task Program tab this engine has been tested against names
  // itself "<STATION> MMDD" (e.g. "MADINAH 0901" = September 1st), which is a reliable signal
  // once read from the sheet's NAME rather than its cell content. Returns {month, day} (1-12,
  // 1-31) or null if the name doesn't end in 4 digits that form a plausible month/day.
  function parseDateFromSheetName(name) {
    const m = /(\d{2})(\d{2})\s*$/.exec(String(name).trim());
    if (!m) return null;
    const month = parseInt(m[1], 10);
    const day = parseInt(m[2], 10);
    if (month < 1 || month > 12 || day < 1 || day > 31) return null;
    return { month, day };
  }

  // One date per day-sheet, in workbook order. If every day-sheet's name carries a real date
  // (the common case), that's authoritative -- this is what lets a supervisor drop a Task
  // Program covering a wider range than they want to run and pick out just the days between
  // startDate/endDate, instead of the file's first tab always being forced to mean startDate
  // itself. The year isn't in the sheet name, so it starts from startDate's year and rolls
  // forward whenever a sheet's month/day would otherwise fall before the previous sheet's date
  // (a range crossing into January). Falls back to the old "sheet N is startDate + N days"
  // assumption, unchanged, for any file whose day-sheets don't all carry a parseable date.
  function deriveSheetDates(daySheets, startDate) {
    const parsed = daySheets.map((s) => parseDateFromSheetName(s.ws.name));
    if (!parsed.length || parsed.some((p) => !p)) {
      return daySheets.map((s) => addDays(startDate, s.idx));
    }
    let year = startDate.getFullYear();
    let prev = null;
    return parsed.map((p) => {
      let d = new Date(year, p.month - 1, p.day);
      if (prev && d < prev) { year += 1; d = new Date(year, p.month - 1, p.day); }
      prev = d;
      return d;
    });
  }

  // --- Task Program parsing -----------------------------------------------------------------
  // One tab per day. endDate is optional (omit to process every day-sheet in the file, the old
  // behavior); when given, only day-sheets whose derived date falls within
  // [startDate, endDate] (inclusive) are returned -- see deriveSheetDates() above for how each
  // sheet's actual date gets determined.
  function parseTaskProgram(workbook, startDate, endDate) {
    const days = [];
    const daySheets = workbook.worksheets
      .map((ws, idx) => ({ ws, idx, tasksCell: findHeaderCell(ws, "Tasks", 15) }))
      .filter((s) => s.tasksCell);
    const sheetDates = deriveSheetDates(daySheets, startDate);
    const rangeStart = endDate ? addDays(startDate, 0).getTime() : null;
    const rangeEnd = endDate ? addDays(endDate, 0).getTime() : null;

    daySheets.forEach((s, i) => {
      const { ws, idx, tasksCell } = s;
      const nameCell = findHeaderCell(ws, "NAME", 15);
      if (!nameCell) throw new Error(`Sheet "${ws.name}" has a "Tasks" column but no "NAME" column next to it.`);
      const startCell = findHeaderCell(ws, "Start", 15);
      const endCell = findHeaderCell(ws, "End", 15);

      const date = sheetDates[i];
      if (rangeStart != null) {
        const t = addDays(date, 0).getTime();
        if (t < rangeStart || t > rangeEnd) return;
      }

      const tasks = [];
      for (let r = tasksCell.row + 1; r <= ws.rowCount; r++) {
        const taskCell = ws.getRow(r).getCell(tasksCell.col);
        const raw = displayValue(taskCell);
        const code = typeof raw === "string" ? raw.trim() : null;
        if (code && /^\d{3,4}\/\d{0,2}[A-Za-z]{1,3}$/.test(code)) {
          // A real Task Program leaves the Start CELL blank for reserve-type tasks (bare R/RA/RB/RC
          // suffix codes) even though the code's own leading digits already say the intended time --
          // confirmed directly against a real file: "0500/7A" has a real Start cell (05:00) right next
          // to "0500/7R"/"0500/7RA" with a genuinely empty one, same leading digits. Falling through
          // to null here was a real, serious bug: recordAssignment stores task.startMin as a driver's
          // lastDutyStartMin/lastDutyEndMin verbatim, so a null start silently erased that driver's
          // rest-time and same-shift-forward history from that task onward -- not a wrong time, a
          // MISSING one, letting the very next real duty's rest-time and rule-4 checks both pass
          // unconditionally regardless of how close together they actually were. The code's own digits
          // are exactly as authoritative as a real Start cell (the one real counter-example available,
          // "0500/7A", agrees with its Start cell exactly), so they're the correct fallback, not a
          // guess.
          const startMin = (startCell ? timeCellToMinutes(displayValue(ws.getRow(r).getCell(startCell.col))) : null) ?? deriveStartMinFromCode(code);
          const endMin = endCell ? timeCellToMinutes(displayValue(ws.getRow(r).getCell(endCell.col))) : null;
          tasks.push({
            row: r, code, kind: classifyCode(code), destination: classifyDestination(code),
            startMin, endMin, isPassengerLeg: isPassengerLegCell(taskCell),
          });
        }
      }
      days.push({
        sheetIndex: idx, sheetName: ws.name, date, dateKey: dateKey(date),
        taskCol: tasksCell.col, nameCol: nameCell.col,
        startCol: startCell ? startCell.col : null, endCol: endCell ? endCell.col : null, tasks,
      });
    });
    return days;
  }

  // Where "Add Task" (and an engine-added reserve) should write its next new row -- one past the
  // last row parseTaskProgram recognized as a real task is NOT reliably blank. Confirmed directly
  // against a real file: every single day-sheet in this station's real template carries a stray
  // "Tasks" label (plus a broken cross-workbook VLOOKUP formula) in that exact row, left over as
  // part of that day's Gantt-chart header/footer furniture -- the same row's columns further right
  // hold "REAL / Start / 1..24 / End / REAL". Blindly assuming maxRow+1 is free silently
  // overwrote that label with the first added task's own code/driver, every single day, on a real
  // engine-downloaded file diffed against its original. Scans forward in the RAW sheet (not just
  // what parseTaskProgram recognized as a task) until both the code and name cells of a candidate
  // row are genuinely blank. Capped well past any real file's own blank-row stretch (confirmed
  // 80+ rows) so a malformed sheet fails loudly instead of scanning forever.
  function findNextFreeTaskRow(taskWorkbook, day) {
    const lastRealTaskRow = day.tasks.reduce((m, t) => Math.max(m, t.row), 0);
    if (lastRealTaskRow === 0) return 200; // no real tasks at all this day -- no row to anchor off of
    const ws = taskWorkbook.worksheets[day.sheetIndex];
    let row = lastRealTaskRow + 1;
    const giveUpAt = lastRealTaskRow + 500;
    while (row < giveUpAt) {
      const codeBlank = displayValue(ws.getRow(row).getCell(day.taskCol)) == null;
      const nameBlank = displayValue(ws.getRow(row).getCell(day.nameCol)) == null;
      if (codeBlank && nameBlank) return row;
      row++;
    }
    throw new Error(`Could not find a genuinely blank row on sheet "${day.sheetName}" within 500 rows of the last real task -- refusing to guess.`);
  }

  // A completed/partially-completed Task Program's NAME cell resolves to a real driver as
  // "<possible 'T- ' prefix><ID>-<NAME><phone, no separator>" (a VLOOKUP result, same format
  // formatDriverForTaskCell below writes). Reading that directly -- rather than only ever
  // trusting this engine's own in-memory task.driver -- is what lets a supervisor drop a REAL,
  // already-partly-staffed month (not a blank one) and have every already-answered task
  // recognized and left alone, instead of silently treated as open.
  function readResolvedCell(cell) {
    let v = cell.value;
    if (v && typeof v === "object" && !(v instanceof Date) && "result" in v) {
      v = v.result;
      if (v && typeof v === "object" && "error" in v) return null;
    }
    return v;
  }

  function parseResolvedNameCell(text) {
    const s = String(text);
    const idMatch = /(\d{5,8})/.exec(s);
    if (!idMatch) return null;
    const id = idMatch[1];
    const afterId = s.slice(idMatch.index + id.length).replace(/^[\s-]+/, "");
    const name = afterId.replace(/\d+\s*$/, "").trim();
    return { id, name: name || null };
  }

  // Reads every task's EXISTING NAME cell straight from the workbook and, for any that already
  // has real content, records it on the task itself: task.originalDriverRawText (the raw resolved
  // text, whether or not it matches a roster driver -- the "there is already a real answer here,
  // don't touch it" signal) and task.originalDriverId + task.driver (only set when that content
  // resolves to an id actually present in rosterData -- lets the UI show the real name and lets
  // rest-time/rotation history correctly count it). A task with nothing in its NAME cell gets
  // neither set, and is untouched -- exactly the same as before this function existed. Called once
  // right after parseTaskProgram, before anything else (Generate, the UI) ever looks at task.driver.
  function resolveExistingTaskAssignments(taskDays, taskWorkbook, rosterData) {
    taskDays.forEach((day) => {
      const ws = taskWorkbook.worksheets[day.sheetIndex];
      day.tasks.forEach((task) => {
        const raw = readResolvedCell(ws.getRow(task.row).getCell(day.nameCol));
        if (raw == null || String(raw).trim() === "") return;
        task.originalDriverRawText = String(raw);
        const parsed = parseResolvedNameCell(raw);
        if (!parsed) return;
        task.originalDriverId = parsed.id;
        const driver = rosterData.drivers.find((d) => d.id === parsed.id);
        if (driver) task.driver = driver;
      });
    });
  }

  // "SD" (and the same lettered-sequence variants reserve slots use -- SDB, SDC, SDD, ...) marks
  // a driver confined to office duty for the day -- confirmed directly: possibly a violation or
  // other administrative reason, "they cannot work as a reserve or take a trip... stuck to what
  // the task origin task folder said." Only meaningful for a task the ORIGINAL file already
  // resolved to a real driver -- a task the engine itself creates never uses this code.
  function isOfficeDutyCode(code) {
    const m = /^(\d{3,4})\/(\d{0,2})([A-Za-z]{1,3})\s*$/.exec(String(code).trim());
    if (!m) return false;
    return m[3].toUpperCase().startsWith("SD");
  }

  // A pre-existing SD task is already never touched or reassigned (same guarantee every other
  // real originalDriverRawText task gets) -- the gap this closes is the OTHER direction: nothing
  // stops that same driver from ALSO being handed a reserve or trip that same day, since the
  // per-day availability check only ever looks at the Roster's own status cell, never at whether
  // the Task Program already has this driver on a real task. Confirmed fix: rather than adding a
  // separate cross-check into the per-task loop, write the SD code straight into the driver's
  // Roster cell for that date -- the EXISTING isAvailable() contract ("blank = available")
  // then excludes them from everything else on its own, no new logic needed anywhere downstream.
  // Only ever touches a cell that's genuinely blank going in -- a Roster cell the supervisor
  // already filled with something else (a real leave code, or anything else) is left exactly as
  // it was. Called once, right after resolveExistingTaskAssignments and before any Generate.
  function syncOfficeDutyToRoster(taskDays, rosterData) {
    let synced = 0;
    taskDays.forEach((day) => {
      day.tasks.forEach((task) => {
        if (!task.driver || !isOfficeDutyCode(task.code)) return;
        const driver = task.driver;
        if (isAvailable(driver.statusByDateKey[day.dateKey])) {
          driver.statusByDateKey[day.dateKey] = task.code;
          synced++;
        }
      });
    });
    return synced;
  }

  function shuffle(arr) {
    for (let i = arr.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    return arr;
  }

  // Stage 1 baseline: for each day, randomly pair available drivers with that day's task slots,
  // one each, no double-booking. No ratio/shift-lock/rest-time reasoning yet -- that's Stage 2's
  // job, layered on top of this same read/parse/write foundation once it's proven solid.
  function assignSimple(rosterData, taskDays) {
    const perDay = taskDays.map((day) => {
      const available = shuffle(rosterData.drivers.filter((d) => isAvailable(d.statusByDateKey[day.dateKey])));
      const n = Math.min(available.length, day.tasks.length);
      const assignments = [];
      for (let i = 0; i < n; i++) {
        assignments.push({ task: day.tasks[i], driver: available[i] });
      }
      return {
        date: day.date, dateKey: day.dateKey, sheetIndex: day.sheetIndex, nameCol: day.nameCol,
        assignments,
        unassignedTasks: day.tasks.slice(n),
        unassignedDrivers: available.slice(n),
      };
    });
    return { perDay };
  }

  // --- Stage 2: shift-lock rotation, soft ratio balancing, hard rest-time -------------------
  // Everything below builds on the exact same parse/plan/patch shape as Stage 1 -- assignWithConditions()
  // returns the identical {perDay: [{assignments, unassignedTasks, unassignedDrivers, ...}]} shape
  // assignSimple() does, just with a smarter selection than "shuffle and take the first N".

  const SHIFT_NAMES = [
    "Early Morning", "Morning", "Late Morning",
    "Early Afternoon", "Afternoon", "Late Afternoon",
    "Early Night", "Night", "Late Night",
  ];

  function defaultConditions() {
    return {
      // Nine narrower bands, three per period (Morning/Afternoon/Night), replacing the earlier
      // five wide ones. Confirmed directly: a driver's own locked shift was never window-
      // constrained (by design -- the forward/backward window is a shortage-only rescue tool, not
      // a rule for every assignment, per an explicit reversal earlier this session), so a 6-9.5h
      // wide band let a driver's real start time swing all over it while the engine correctly saw
      // it as "no issue, same shift" -- which WAS an issue, just not one the window was ever meant
      // to solve. Narrowing the bands themselves is the fix: "I don't want to see a driver moving
      // or changing his hour a lot and the engine considering it as the same shift... so I'm
      // trying to make this new selection so the engine understand [what] hours [are] acceptable."
      // Clean round-hour boundaries, confirmed directly (replacing an earlier :30/:10/:20-aligned
      // draft) -- still fully editable in the Conditions panel like every other boundary.
      shifts: [
        { name: "Early Morning", start: "03:00", end: "06:00" },
        { name: "Morning", start: "06:00", end: "09:00" },
        { name: "Late Morning", start: "09:00", end: "12:00" },
        { name: "Early Afternoon", start: "12:00", end: "14:00" },
        { name: "Afternoon", start: "14:00", end: "16:00" },
        { name: "Late Afternoon", start: "16:00", end: "18:00" },
        { name: "Early Night", start: "18:00", end: "20:00" },
        { name: "Night", start: "20:00", end: "00:00" },
        { name: "Late Night", start: "00:00", end: "03:00" },
      ],
      ratioReserveDays: 4,
      ratioTripDays: 2,
      restHours: 12,
      shiftLockWeeks: 2,
    };
  }

  function parseHHMM(str) {
    const m = /^(\d{1,2}):(\d{2})$/.exec(String(str || "").trim());
    if (!m) return null;
    const h = parseInt(m[1], 10), mm = parseInt(m[2], 10);
    if (h > 23 || mm > 59) return null;
    return h * 60 + mm;
  }

  function conditionsAreComplete(conditions) {
    if (!conditions) return false;
    const shiftsOk = conditions.shifts.length === SHIFT_NAMES.length
      && conditions.shifts.every((s) => parseHHMM(s.start) != null && parseHHMM(s.end) != null);
    return shiftsOk
      && Number.isFinite(conditions.ratioReserveDays) && conditions.ratioReserveDays >= 0
      && Number.isFinite(conditions.ratioTripDays) && conditions.ratioTripDays >= 0
      && (conditions.ratioReserveDays + conditions.ratioTripDays) > 0
      && Number.isFinite(conditions.restHours) && conditions.restHours >= 0
      && Number.isInteger(conditions.shiftLockWeeks) && conditions.shiftLockWeeks >= 1;
  }

  // Handles a shift window that crosses midnight (e.g. Night 19:00-03:30) the same way a plain
  // one does (e.g. Early Morning 03:30-08:00) -- just two different comparisons depending on
  // which side of midnight the window falls on.
  function minutesInWindow(minutes, startMin, endMin) {
    if (startMin === endMin) return true;
    if (startMin < endMin) return minutes >= startMin && minutes < endMin;
    return minutes >= startMin || minutes < endMin;
  }

  // Circular distance (in minutes, around a 1440-minute day) between two times of day.
  function circularMinuteDist(a, b) {
    const d = Math.abs(a - b) % 1440;
    return Math.min(d, 1440 - d);
  }

  // A task's start time doesn't have to fall inside a configured shift's window to belong to
  // that shift -- if every window is exact and a task starts in a genuine gap between two of
  // them (e.g. a 03:00 task when the earliest shift opens at 03:30), it's assigned to whichever
  // shift's window it's nearest to in clock time, by policy: "consider that the closest shift."
  // An exact window match always wins outright; only a task in a true gap falls back to nearest.
  function classifyShiftForMinutes(conditions, minutes) {
    if (minutes == null) return null;
    let bestIdx = null, bestDist = Infinity;
    for (let i = 0; i < conditions.shifts.length; i++) {
      const s = conditions.shifts[i];
      const startMin = parseHHMM(s.start), endMin = parseHHMM(s.end);
      if (startMin == null || endMin == null) continue;
      if (minutesInWindow(minutes, startMin, endMin)) return i;
      const dist = Math.min(circularMinuteDist(minutes, startMin), circularMinuteDist(minutes, endMin));
      if (dist < bestDist) { bestDist = dist; bestIdx = i; }
    }
    return bestIdx;
  }

  // A driver's locked shift for a given date is computed purely from an anchor point (the date
  // and shift index they were locked into at some point) plus how many whole shiftLockWeeks
  // blocks have elapsed since then, cycling through the fixed Early Morning -> Late Morning ->
  // Early Afternoon -> Late Afternoon -> Night -> repeat order. Computing it this way (rather
  // than storing "current shift" directly) is what lets a later run just keep advancing from
  // wherever a previous run left off, without needing to replay every day in between. Restored
  // for v2's day-by-day supervised workflow -- see assignWithConditions below for why this is
  // safe to bring back after being removed in the whole-month rebuild.
  function computeShiftIndexForDriver(driverState, conditions, date) {
    if (!driverState || !driverState.shiftAnchorDate) return null;
    const anchor = new Date(driverState.shiftAnchorDate + "T00:00:00");
    const target = new Date(dateKey(date) + "T00:00:00");
    const daysBetween = Math.round((target - anchor) / 86400000);
    const weeksElapsed = Math.floor(daysBetween / 7);
    const blocksElapsed = Math.floor(weeksElapsed / conditions.shiftLockWeeks);
    const n = conditions.shifts.length;
    return ((driverState.shiftAnchorIndex + blocksElapsed) % n + n) % n;
  }

  // Total task volume per shift across every day in `taskDays` (a whole loaded month, not just
  // one day) -- confirmed directly: task demand is nowhere near evenly split across the 5 shifts
  // in a real month (one real September ran 34% Early Afternoon vs 2% Night), so a cold-start
  // scheme that spreads drivers evenly across shifts regardless of this shape locks far too many
  // drivers into the light shifts and far too few into the heavy ones -- exactly what was
  // producing the bulk of a real run's unassigned tasks. This is the demand side of the fix;
  // computeShiftSeedAssignment (below) turns it into an actual per-driver shift assignment.
  function computeShiftDemand(taskDays, conditions) {
    const counts = conditions.shifts.map(() => 0);
    taskDays.forEach((day) => {
      day.tasks.forEach((task) => {
        const idx = classifyShiftForMinutes(conditions, task.startMin);
        if (idx != null) counts[idx]++;
      });
    });
    return counts;
  }

  // Same as computeShiftDemand, but only counting tasks that still genuinely need a driver --
  // excludes any task whose NAME cell already had a real pre-existing answer in the original file
  // (see resolveExistingTaskAssignments/task.originalDriverRawText). This is the shape that
  // actually matters for seeding: a real, already-partly-staffed month can have a shift whose
  // TOTAL volume looks modest only because most of it is already covered by real pre-existing
  // assignments, while the REMAINING open gaps in that exact shift are the overwhelming majority
  // of what's left to fill (confirmed directly: one real September's Early Morning was 20% of
  // total demand but 62% of what was still genuinely open). Seeding against total demand in that
  // case starves the shift that actually needs the most new locked drivers. For a genuinely blank
  // month (nothing has a pre-existing answer at all) this returns exactly the same counts as
  // computeShiftDemand -- no behavior change there.
  function computeOpenShiftDemand(taskDays, conditions) {
    const counts = conditions.shifts.map(() => 0);
    taskDays.forEach((day) => {
      day.tasks.forEach((task) => {
        // Also excludes a task this engine invented on the fly as a stopgap for an otherwise-
        // unassigned driver (engineAddedReserve, set by v2's applyReserveAutoFill) -- confirmed as
        // a real, live feedback loop: v2 recomputes this seed fresh on every single day's Generate
        // from the CURRENT livePlan.taskDays, and applyReserveAutoFill permanently splices its new
        // task into that same array. Counting those invented tasks as real "demand" meant every
        // later day's Generate saw a shape that was skewed by how many stopgap reserves earlier
        // days happened to need -- not the real month's shape at all -- so a driver whose very
        // first shift lock landed on, say, day 12 instead of day 1 could get seeded into a
        // completely different shift than day 1 would have given them, for no reason connected to
        // real task demand.
        if (task.originalDriverRawText || task.engineAddedReserve) return;
        const idx = classifyShiftForMinutes(conditions, task.startMin);
        if (idx != null) counts[idx]++;
      });
    });
    return counts;
  }

  // Precomputes a one-time driverId -> shiftIndex map for the WHOLE roster, sized to match the
  // shape of what's still genuinely OPEN (computeOpenShiftDemand above, not the whole month's
  // total demand -- a shift that's mostly already staffed for real shouldn't soak up seed slots
  // its remaining gaps don't need), instead of assignWithConditions's old per-day "spread by
  // position in today's available list" (which spreads evenly regardless of demand). Only ever
  // consulted for a driver's FIRST-EVER shift lock -- anyone carried over from real saved/granted
  // history keeps that real anchor untouched, this is purely for someone
  // who's never been anchored before.
  //
  // Uses the same divisor method real seat-apportionment uses (D'Hondt/Jefferson): walk the
  // roster in a fixed, deterministic order (sorted by id, so re-running against the same files
  // always produces the same assignment) and hand each driver in turn to whichever shift is
  // currently furthest below its share of the demand -- highest share-per-(alreadySeeded+1).
  // This keeps the cumulative mix tracking the real shape at every prefix length, not just once
  // every driver's been placed, and naturally seeds nobody into a shift with zero real demand.
  //
  // Before that proportional pass, though: any shift with SOME real demand -- even a small,
  // occasional amount -- gets one driver locked into it first, as long as there are enough
  // drivers to go around. Pure proportional rounding can otherwise send a low-share shift's seed
  // count all the way to zero (confirmed directly: a shift with ~9% of demand rounded to 0 of 6
  // seeded drivers), which doesn't just make that shift's tasks unlikely to fill -- with nobody
  // ever locked into it, they become permanently unfillable, every single time they occur.
  // Early Morning (shift index 0) is structurally different from every other band: when a task's
  // own-shift pool comes up empty, assignWithConditions widens to exactly the one shift before it
  // in the fixed chain -- except band 0, which has no shift before it to borrow from at all (see
  // "shiftIdx 0 (Early Morning) has no shift before it to borrow from" there). Every other band
  // gets a second chance on a day its own locked drivers happen to be thin; Early Morning never
  // does. Checked against a real month: Early Morning's real demand share is actually modest
  // (~13%, roughly in line with an even 9-way split) -- an earlier "~45%" figure quoted here was
  // wrong, traced to a bug in an offline diagnostic script (it read "already answered" status off
  // an already-generated file, so every task the engine itself successfully filled looked
  // pre-existing, and only Early Morning's OWN leftover failures showed up as "demand" -- circular).
  // With the demand share corrected, Early Morning still filled only 52% of its tasks all month
  // (worst of any band with real demand) purely because it has no rescue when its own thin, and
  // simulating an actual rescue mechanism instead of a seed boost hit the same ~88% ceiling --
  // the real constraint is that roughly HALF the entire roster is off on any given day, every day,
  // all month (leave/vacation/training), not something either fix can conjure past. Confirmed
  // decision: still worth a boost as a real, if modest, improvement -- 2.0x empirically gave the
  // best result of the values tested (1.0x-5.0x) against the real month's data before returns
  // turn negative from starving other bands.
  const EARLY_MORNING_SEED_BOOST = 2.0;

  // computeOpenShiftDemand's own share for a shift can run far higher than that shift's TRUE
  // (filled+open) demand share, purely as a function of how much of the loaded month happens to
  // already be resolved when Generate runs -- confirmed as a real, separate bug from a real
  // supervisor's file: Early Morning's TRUE share was a healthy ~15% (matching the ~13% this
  // boost was originally tuned against), but with 16 of 30 loaded days already resolved, its OPEN
  // share alone had already drifted to 41% (every remaining day's own Early Morning gap piling
  // onto the same measurement -- itself partly a symptom of the exact shortage being diagnosed).
  // Multiplying THAT by the boost pushed 59 of 99 drivers (60%) onto Early Morning, starving
  // every other shift, while the day this was traced from still had zero of them actually
  // available -- headcount was never the bottleneck, availability was. Bounding the boosted share
  // at (2x the TRUE share) rather than (2x the OPEN share) keeps the exact behavior this was
  // tuned against on a fresh, unresolved month (where open share ≈ true share, so this bound
  // never actually engages) while preventing the runaway on a month that's mostly already staffed
  // by the time Generate runs.
  function computeShiftSeedAssignment(rosterData, taskDays, conditions) {
    const demand = computeOpenShiftDemand(taskDays, conditions);
    const totalDemandCounts = computeShiftDemand(taskDays, conditions);
    const n = conditions.shifts.length;
    const totalDemand = demand.reduce((a, b) => a + b, 0);
    const totalDemandAll = totalDemandCounts.reduce((a, b) => a + b, 0);
    // No task data to learn a shape from at all -- fall back to the plain even split this engine
    // used before this feature existed, rather than pretending to know a distribution.
    const shares = totalDemand > 0 ? demand.map((c) => c / totalDemand) : demand.map(() => 1 / n);
    if (shares[0] > 0) {
      const trueShare0 = totalDemandAll > 0 ? totalDemandCounts[0] / totalDemandAll : shares[0];
      shares[0] = Math.min(shares[0], trueShare0) * EARLY_MORNING_SEED_BOOST;
    }

    const assignment = {};
    const seededCount = new Array(n).fill(0);
    const sortedDrivers = rosterData.drivers.slice().sort((a, b) => String(a.id).localeCompare(String(b.id)));

    let nextDriver = 0;
    const shiftsWithDemand = shares.map((s, i) => i).filter((i) => shares[i] > 0);
    for (const shiftIdx of shiftsWithDemand) {
      if (nextDriver >= sortedDrivers.length) break; // roster too small to floor every shift -- proportional pass below still covers the rest
      assignment[sortedDrivers[nextDriver].id] = shiftIdx;
      seededCount[shiftIdx] = 1;
      nextDriver++;
    }

    for (; nextDriver < sortedDrivers.length; nextDriver++) {
      let bestIdx = 0, bestScore = -Infinity;
      for (let i = 0; i < n; i++) {
        const score = shares[i] / (seededCount[i] + 1);
        if (score > bestScore) { bestScore = score; bestIdx = i; }
      }
      assignment[sortedDrivers[nextDriver].id] = bestIdx;
      seededCount[bestIdx]++;
    }
    return assignment;
  }

  function minutesBetween(dateKeyA, minA, dateKeyB, minB) {
    const dA = new Date(dateKeyA + "T00:00:00");
    const dB = new Date(dateKeyB + "T00:00:00");
    return Math.round((dB - dA) / 60000) - minA + minB;
  }

  // A duty whose end time is numerically smaller than its start time (Night: 20:00 start, 03:30
  // end) actually ends on the CALENDAR DAY AFTER the day it was assigned for, not the same day --
  // confirmed as a real, serious bug: recording lastDutyEndDateKey as the assigned-for day
  // regardless overstated the rest gap to the next duty by exactly 24 hours for anyone whose last
  // duty crossed midnight, letting the supposedly-hard 12-hour rest rule silently pass a
  // back-to-back (or near-zero-gap) transition -- e.g. a driver's Night shift truly ending 03:30
  // the next morning, immediately followed by an Early Morning duty starting at that same 03:30,
  // computed as a full 24h of rest instead of the true 0. day.date is this duty's assigned-for
  // day; addDays(day.date, 1) is only used when the duty actually wraps past midnight.
  function dutyEndDateKey(day, startMin, endMin) {
    return endMin != null && endMin < startMin ? dateKey(addDays(day.date, 1)) : day.dateKey;
  }

  // How much a driver is "owed" of a given kind (reserve vs trip) relative to the configured
  // ratio -- a positive number means they've been getting less of that kind than the target
  // ratio calls for, so they're preferred for it. Judged against CUMULATIVE counts (every trip
  // and reserve this driver has ever had in this rotationState, not just a short rolling window)
  // -- a rolling window only ever prevents short-term streaks, it can't correct an imbalance that
  // built up earlier in the month, which is exactly what real monthly totals showed: some drivers
  // at 1 trip / 7 reserve, others at 10 trips / 1 reserve, despite the rolling-window rules never
  // being individually violated at any single point in time. This is still the "soft rule"
  // version: a preference used to sort candidates, never a hard filter, so it can't itself cause
  // a task to go unfilled the way the rest-time check can.
  // targetReserveFrac: the reserve share to compare this driver against -- see
  // groupReserveFrac() in assignWithConditions for where this actually comes from (each
  // driver's own shift-peer group's real running average, not a fixed configured number).
  // A pure sort-order nudge toward the configured ratio -- never a hard exclusion. Confirmed
  // against a real completed month that this is the right shape: real reserve/trip totals vary
  // driver to driver on their own (roughly 0.5x-4x the target ratio in practice), so forcing
  // everyone toward a tight band doesn't match how this actually gets done by hand. A hard quota
  // was tried and removed -- once a fixed target became unreachable for part of the roster (real
  // task supply skews toward reserve some days), the exclusion just had to keep getting widened
  // and second-guessed. A soft nudge plus "don't repeat yesterday's kind" (isRepeatingLastKind
  // below) is simpler and matches the real spread better. A genuine 3-in-a-row streak of the same
  // kind (RRR or TTT) is preferred against even more strongly (see wouldBeThirdConsecutiveKind,
  // applied in assignWithConditions's candidate cascade) -- but like everything else here, it's a
  // preference, not a hard rule: "if there is no other choice than giving a driver three
  // consecutive days as a reserve, we can do it... we will not keep these drivers with no job."
  function ratioPreference(driverState, targetReserveFrac, wantKind) {
    const totalReserve = driverState.cumulativeReserve || 0;
    const totalTrip = driverState.cumulativeTrip || 0;
    const total = totalReserve + totalTrip;
    if (!total) return 0;
    const targetFrac = wantKind === "reserve" ? targetReserveFrac : 1 - targetReserveFrac;
    const actualFrac = (wantKind === "reserve" ? totalReserve : totalTrip) / total;
    return targetFrac - actualFrac;
  }

  // A driver can still hit their overall ratio while every reserve day comes first and every
  // trip day comes last (RRRTTT). Explicit policy: "make it a mix, one day reserve one day
  // trip... do not put it in a sequence." A driver whose most recent assignment was already this
  // same kind is preferred against (not hard-excluded -- see assignWithConditions, this only
  // narrows the candidate pool when it wouldn't leave the task unfilled) for another one of that
  // kind -- this is what actually forces alternation (RTRTRT) instead of just capping the total.
  function isRepeatingLastKind(driverState, wantKind) {
    const kinds = driverState.recentKinds || [];
    if (!kinds.length) return false;
    return kinds[kinds.length - 1] === wantKind;
  }

  // isRepeatingLastKind above only ever looks one day back -- a candidate pool could still drift
  // through RRRRRT or RRRTTT one single-day repeat at a time even though the ratio itself stayed
  // on target. Confirmed unacceptable directly: "reserve reserve reserve / trip trip trip" and
  // "reserve reserve reserve reserve reserve trip" are NOT okay -- the real requirement is a
  // genuine mix (RTRTRT ideally, RTRRTR at worst if a perfect alternation can't be reached), tied
  // to real weekly driving-hour rules that need a trip to actually trigger periodically rather
  // than a driver sitting on reserve for days running. This is checked as a STRONGER preference
  // than isRepeatingLastKind (see the candidate cascade in assignWithConditions: try full
  // alternation first, then "one repeat but not a third in a row," and only fall back to allowing
  // an actual 3-in-a-row when every other candidate has been exhausted) -- explicitly NOT a hard
  // exclusion: "if there is no other choice than giving a driver three consecutive days as a
  // reserve, we can do it... we will not keep these drivers with no job." A driver already idle
  // that day because of this preference matters more than the streak itself.
  function wouldBeThirdConsecutiveKind(driverState, wantKind) {
    const kinds = driverState.recentKinds || [];
    if (kinds.length < 2) return false;
    return kinds[kinds.length - 1] === wantKind && kinds[kinds.length - 2] === wantKind;
  }

  // A real, confirmed gap: wouldBeThirdConsecutiveKind above only ever narrows the pool down to
  // "avoid becoming a 3rd in a row" -- past that, the per-task loop's cascade fell all the way
  // back to the FULL unfiltered pool with no further distinction at all between a driver about to
  // become a 4th-in-a-row and one about to become a 7th. Confirmed against a real exported month:
  // one driver hit 6 consecutive reserve days this way. "No 4 consecutive... soft preference with
  // last-resort escape valve" means 4 is the escape valve, not an open door past 3 -- so this adds
  // the missing middle tier (prefer avoiding a 4th too), with the TRUE last resort (see
  // assignWithConditions) now reserved only for when literally nobody can avoid a 4th, and even
  // then preferring whoever's current streak is shortest so the burden doesn't keep landing on the
  // same driver day after day.
  function wouldBeFourthConsecutiveKind(driverState, wantKind) {
    const kinds = driverState.recentKinds || [];
    if (kinds.length < 3) return false;
    return kinds[kinds.length - 1] === wantKind && kinds[kinds.length - 2] === wantKind && kinds[kinds.length - 3] === wantKind;
  }

  // How many trailing entries of recentKinds already equal wantKind -- used only as a last-resort
  // tie-break (see assignWithConditions) once every candidate is already guaranteed to exceed the
  // preferred 3-in-a-row cap, so the pick at least goes to whoever's shallowest into that streak
  // rather than piling an even longer one onto whoever happens to sort first otherwise.
  function currentStreakLength(driverState, wantKind) {
    const kinds = driverState.recentKinds || [];
    let n = 0;
    for (let i = kinds.length - 1; i >= 0 && kinds[i] === wantKind; i--) n++;
    return n;
  }

  // rotationState: { [driverId]: { lastDutyEndDateKey, lastDutyEndMin, recentKinds: [],
  // cumulativeReserve, cumulativeTrip } } -- passed in and mutated in place so the caller can
  // persist it (e.g. to localStorage per station) and hand it back in on the next run to
  // continue every driver's rest-time/ratio history instead of restarting cold.
  // specialRules (optional): per-driver overrides layered on top of the general rules, e.g. a
  // named driver who should never take a sweep, or should be steered toward/away from trips to
  // a particular destination. Each entry: { match(driver) => bool, excludeKinds: [...],
  // tripDestinationBias: {KAIA:n, MAK:n, MAD:n}, passengerLegBonus: {KAIA:n, MAK:n, MAD:n} }.
  // excludeKinds is a hard filter (that driver is never even a candidate for that task kind);
  // the bias fields are soft nudges added to the normal ratio-preference sort score, so they
  // steer selection without ever overriding the hard rest-time rule or leaving a task unfilled
  // when this driver was the only option.
  function isExcludedBySpecialRule(driver, task, specialRules) {
    return specialRules.some((rule) => rule.match(driver) && rule.excludeKinds && rule.excludeKinds.includes(task.kind));
  }
  function specialRuleBias(driver, task, specialRules) {
    if (task.kind !== "trip" || !task.destination) return 0;
    let bias = 0;
    specialRules.forEach((rule) => {
      if (!rule.match(driver)) return;
      if (rule.tripDestinationBias) bias += rule.tripDestinationBias[task.destination] || 0;
      if (task.isPassengerLeg && rule.passengerLegBonus) bias += rule.passengerLegBonus[task.destination] || 0;
    });
    return bias;
  }

  // When several reserve tasks share the exact same start time, filling all of them stacks
  // redundant standby coverage at one moment while a distinct, later reserve slot can go
  // completely uncovered with no driver at all -- reported directly against a real day, twice:
  // first two drivers both sitting reserve at the same time while late-shift slots showed no
  // name, then (after a first attempt at this fix that only separated "first at a time" from
  // "any repeat") three consecutive reserve slots at 09:00 all filled while slots at 12:00 and
  // 13:00 that ALSO had duplicates went empty -- because every duplicate, regardless of which
  // time it belonged to, was still being tried in plain chronological order, so an early time's
  // 2nd or 3rd slot could exhaust the driver pool before a later time's 2nd slot ever got a turn.
  // The actual fix has to be a round-robin by depth, not just a two-tier split: rank every
  // reserve task by its position among same-time siblings (1st, 2nd, 3rd, ...), then process
  // every time's 1st slot (in time order) before any time's 2nd slot, every 2nd before any 3rd,
  // and so on. That's what guarantees a distinct time's first shot at coverage always outranks
  // a DIFFERENT time's second-or-later slot, no matter how early or late either time falls in
  // the day. Only reordering; every task is still attempted exactly once.
  function spreadReserveTasks(reserveTasks) {
    const byStartMin = {};
    reserveTasks.forEach((t) => { (byStartMin[t.startMin] = byStartMin[t.startMin] || []).push(t); });
    // Object keys that look like non-negative integers (every startMin here) always iterate in
    // ascending numeric order in JS, regardless of insertion order -- this naturally walks times
    // chronologically without needing an explicit sort.
    const times = Object.keys(byStartMin);
    const maxDepth = Math.max(0, ...times.map((t) => byStartMin[t].length));
    const result = [];
    for (let depth = 0; depth < maxDepth; depth++) {
      times.forEach((t) => {
        if (byStartMin[t][depth]) result.push(byStartMin[t][depth]);
      });
    }
    return result;
  }

  // "Chain Rescue" -- runs after the normal per-task assignment loop and before reserve auto-fill
  // (buildReserveTasksForUnassignedDrivers, just below), for any real Task Program duty still
  // unfilled. Built and validated against real September data across many rounds of testing
  // before shipping: a naive "give any idle driver the nearest open task" pass was tried first and
  // rejected -- it filled real gaps, but sometimes by handing a driver locked to one shift a task
  // hours away from it (confirmed directly, e.g. a driver locked to Late Afternoon getting an
  // 08:00 Morning task) purely because they happened to be free and clear rest-time, the same
  // "far jump" problem rule 4/6 already exist to prevent everywhere else in this engine. The
  // design below fixes that: a free driver may only be placed directly onto a duty in the LATEST
  // shift band that still has any shortage that day (see latestActiveBand below) -- everywhere
  // earlier must be reached by an actual backward CHAIN of small hops through already-filled
  // drivers, each one individually rest-time-checked, never one person making a single long jump.

  // Not every open reserve-kind duty matters equally. Confirmed directly: several reserve slots at
  // the same sign-in time (e.g. four 0800/7R* rows) are redundant copies of the same duty -- only
  // ONE needs a driver to satisfy that time band, the rest can stay open with no real consequence.
  // The one exception is a code ending in "RK": despite reading as a reserve code (classifyCode
  // sees the "R" and calls it "reserve"), confirmed directly it's actually a real trip -- the
  // driver travels to another city to stand reserve THERE -- so it's mandatory like any other trip
  // or sweep, never treated as a spare duplicate.
  function chainRescueSuffix(code) {
    const m = /^(\d{3,4})\/(\d{0,2})([A-Za-z]{1,3})\s*$/.exec(String(code).trim());
    return m ? m[3].toUpperCase() : null;
  }
  function isChainRescueMandatory(task) {
    if (task.kind === "trip" || task.kind === "sweep") return true;
    return chainRescueSuffix(task.code) === "RK";
  }
  // Every still-open mandatory duty, plus (for each same-time reserve-pool group with NOTHING
  // filled yet) one representative -- once any one member of a group has a driver, the rest of
  // that group is no longer a real gap and is left out of this list entirely.
  function chainRescueOpenDuties(day) {
    const mandatoryOpen = day.tasks.filter((t) => !t.driver && isChainRescueMandatory(t));
    const lenientTasks = day.tasks.filter((t) => t.kind === "reserve" && chainRescueSuffix(t.code) !== "RK");
    const groups = {};
    lenientTasks.forEach((t) => (groups[t.startMin] = groups[t.startMin] || []).push(t));
    const lenientOpen = [];
    Object.values(groups).forEach((group) => {
      if (group.some((t) => t.driver)) return;
      lenientOpen.push(group[0]);
    });
    return mandatoryOpen.concat(lenientOpen);
  }
  // A reserve-pool group's 2nd+ filled member is a spare duplicate -- their own group's "at least
  // one" requirement is already satisfied by whichever member is kept, so freeing the rest costs
  // nothing and needs no backfill. Confirmed directly against real data: this is real, safe
  // manpower a supervisor would recognize as available, not people who need replacing first.
  function chainRescueSparePool(day) {
    const groups = {};
    day.tasks.forEach((t) => {
      if (t.kind === "reserve" && chainRescueSuffix(t.code) !== "RK" && t.driver) {
        (groups[t.startMin] = groups[t.startMin] || []).push(t);
      }
    });
    const spares = [];
    Object.values(groups).forEach((g) => { if (g.length > 1) spares.push(...g.slice(1)); });
    return spares;
  }
  function chainRescuePassesRest(conditions, rotationState, driverId, day, task) {
    const st = rotationState[driverId];
    if (!st) return false;
    if (st.lastDutyEndMin != null) {
      const gap = minutesBetween(st.lastDutyEndDateKey, st.lastDutyEndMin, day.dateKey, task.startMin);
      if (gap < conditions.restHours * 60) return false;
    }
    return true;
  }
  // Chain Rescue is a real assignment, same as anything else this engine hands out -- it should
  // respect the same soft "avoid a 4th+ consecutive same-kind duty" preference the normal
  // per-task loop already applies (wouldBeFourthConsecutiveKind), not just rest-time. Confirmed as
  // a real gap in testing: the live audit flagged drivers picked up a 4th-straight reserve day
  // purely because Chain Rescue's candidate order never considered it. Same shape as everywhere
  // else in this engine -- a preference, not a hard exclusion, so it only narrows the candidate
  // list when a better option actually exists.
  function chainRescueWouldBeFourthConsecutive(rotationState, driverId, task) {
    const st = rotationState[driverId];
    if (!st) return false;
    const wantKind = task.kind === "reserve" ? "reserve" : "trip";
    return wouldBeFourthConsecutiveKind(st, wantKind);
  }
  // Confirmed as a real, live bug: a direct placement (see tryFill in buildChainRescueMoves below)
  // only ever checked rest-time, never how far the target band is from the driver's own locked
  // shift -- so a driver locked to Early Night could get placed directly at Early Morning purely
  // because that happened to be the day's only remaining shortage, a 6-band, ~9-hour swing from
  // where they actually belong. Confirmed directly against real September data: RAKAN NAFEA N
  // ALHAISONI (locked Early Night) placed at 05:30 with nothing else touched that day. Distance is
  // wrap-aware (9 bands run in a real 24h loop -- Late Night(8) sits right next to Early
  // Morning(0), not six bands away).
  function chainRescueBandDistance(a, b) {
    const raw = Math.abs(a - b);
    return Math.min(raw, 9 - raw);
  }
  // Preferred/max backward-hop step, in minutes -- tested directly against real September data.
  // 90min covers the overwhelming majority of real hops needed; a small number of days have a
  // genuine 2+ hour hole in the day's own task schedule (nothing sits between two real tasks close
  // enough), and 90min alone leaves those unreachable even though every individual hop would
  // otherwise be perfectly rest-time-safe. 180min was the smallest widening that closed those
  // gaps in testing without ever needing to go further.
  const CHAIN_RESCUE_PREFERRED_STEP_MIN = 90;
  const CHAIN_RESCUE_MAX_STEP_MIN = 180;

  // Builds the day's Chain Rescue plan without mutating anything -- `freeDrivers` is whatever the
  // caller has already identified as available (its own currently-idle drivers plus
  // chainRescueSparePool's spare duplicates); day.tasks is read as-is (spare duplicate tasks are
  // excluded from the hop candidate pool below, since their driver is being freed regardless of
  // whether this plan ends up using them for anything).
  // Returns:
  //   moves: [{task, driver, vacatedTask}] -- task gets driver; vacatedTask (null for a driver
  //     coming straight from freeDrivers) is the task that same driver is being moved OFF of, and
  //     is itself covered by its own separate entry in this same list (a hop's source task always
  //     gets refilled by the next link in the chain, never left half-done).
  //   stillFreeDrivers: freeDrivers not used by any move.
  function buildChainRescueMoves(day, conditions, rotationState, freeDrivers) {
    const spareTaskSet = new Set(chainRescueSparePool(day));
    const filledByBand = {};
    day.tasks.forEach((t) => {
      if (!t.driver || spareTaskSet.has(t)) return;
      const idx = classifyShiftForMinutes(conditions, t.startMin);
      (filledByBand[idx] = filledByBand[idx] || []).push({ task: t, driver: t.driver });
    });

    const openDuties = chainRescueOpenDuties(day);
    const openByBand = {};
    openDuties.forEach((t) => {
      const idx = classifyShiftForMinutes(conditions, t.startMin);
      (openByBand[idx] = openByBand[idx] || []).push(t);
    });
    const activeBands = Object.keys(openByBand).map(Number);
    const latestActiveBand = activeBands.length ? Math.max(...activeBands) : -1;

    const moves = [];
    const usedDriverIds = new Set();
    const reassignedTasks = new Set();

    function tryFill(task, band, visited) {
      if (band === latestActiveBand) {
        const restEligible = freeDrivers.filter((d) => !usedDriverIds.has(d.id) && chainRescuePassesRest(conditions, rotationState, d.id, day, task));
        // Graduated by how close the driver's OWN locked shift is to this band -- exact match
        // first, then adjacent, only falling all the way through to "anyone at all" if genuinely
        // nobody shift-appropriate is available. Same "prefer close, widen only when truly empty"
        // shape as everywhere else in this engine (see SMOOTH_FORWARD_STEP_TIERS_MIN), applied here
        // for the first time to direct placements specifically.
        const withDistance = restEligible.map((d) => {
          const st = rotationState[d.id];
          const ownIdx = st ? computeShiftIndexForDriver(st, conditions, day.date) : null;
          return { d, distance: ownIdx != null ? chainRescueBandDistance(ownIdx, band) : 999 };
        });
        const exact = withDistance.filter((x) => x.distance === 0);
        const near = withDistance.filter((x) => x.distance === 1);
        const tiered = exact.length ? exact : near.length ? near : withDistance;
        const notFourth = tiered.filter((x) => !chainRescueWouldBeFourthConsecutive(rotationState, x.d.id, task));
        const chosen = (notFourth.length ? notFourth : tiered)[0];
        if (chosen) {
          usedDriverIds.add(chosen.d.id);
          return { driver: chosen.d, vacatedTask: null };
        }
      }
      if (band < 8) {
        const candidates = (filledByBand[band + 1] || [])
          .filter((a) => !reassignedTasks.has(a.task) && !usedDriverIds.has(a.driver.id))
          .map((a) => ({ a, step: a.task.startMin - task.startMin }))
          .filter(({ step }) => step >= 0 && step <= CHAIN_RESCUE_MAX_STEP_MIN)
          .sort((x, y) => x.step - y.step);
        const preferred = candidates.filter((c) => c.step <= CHAIN_RESCUE_PREFERRED_STEP_MIN);
        const ordered = preferred.length ? preferred.concat(candidates.filter((c) => c.step > CHAIN_RESCUE_PREFERRED_STEP_MIN)) : candidates;
        const restEligible = ordered.filter(({ a }) => !visited.has(a.task) && chainRescuePassesRest(conditions, rotationState, a.driver.id, day, task));
        // Preferred tier first (small step, not a 4th-consecutive), but if literally none of THAT
        // tier's recursion pans out, still fall through to the excluded ones rather than giving up
        // a chain that a less-ideal candidate could have completed -- a real gap in an earlier
        // version of this, which stopped trying entirely once the preferred tier was non-empty
        // even if every one of them turned out to be a recursive dead end.
        const notFourth = restEligible.filter(({ a }) => !chainRescueWouldBeFourthConsecutive(rotationState, a.driver.id, task));
        const fourthOnly = restEligible.filter(({ a }) => chainRescueWouldBeFourthConsecutive(rotationState, a.driver.id, task));
        const finalOrder = notFourth.concat(fourthOnly);
        for (const { a } of finalOrder) {
          const refill = tryFill(a.task, band + 1, new Set([...visited, a.task]));
          if (refill) {
            reassignedTasks.add(a.task);
            usedDriverIds.add(a.driver.id);
            moves.push({ task: a.task, driver: refill.driver, vacatedTask: refill.vacatedTask });
            return { driver: a.driver, vacatedTask: a.task };
          }
        }
      }
      return null;
    }

    for (let band = 0; band <= 8; band++) {
      const opens = (openByBand[band] || []).slice().sort((t1, t2) => {
        const kindRank = (t) => (isChainRescueMandatory(t) ? 0 : 1);
        return kindRank(t1) - kindRank(t2) || t1.startMin - t2.startMin;
      });
      opens.forEach((task) => {
        const result = tryFill(task, band, new Set([task]));
        if (result) moves.push({ task, driver: result.driver, vacatedTask: result.vacatedTask });
      });
    }
    const stillFreeDrivers = freeDrivers.filter((d) => !usedDriverIds.has(d.id));
    return { moves, stillFreeDrivers };
  }

  // Real reserve codes carry a route digit before the letters ("0700/7RA") -- confirmed as the
  // convention to use for newly-created ones, matching how the overwhelming majority of real
  // reserve tasks are already written (a small minority use no digit at all, e.g. "1100/RA", but
  // that's the exception, not the rule to build new ones on).
  const RESERVE_ROUTE_DIGIT = "7";
  // Fixed slot order at a single sign-in time -- confirmed directly: "sign in time 7am, you can
  // add 4 R task as max: 0700/R, 0700/RA, 0700/RB, 0700/RC." Never more than 4 at one time.
  const RESERVE_SUFFIXES = ["R", "RA", "RB", "RC"];
  const MAX_RESERVE_SLOTS_PER_TIME = RESERVE_SUFFIXES.length;
  // Confirmed directly against real files: every "7R*"-coded reserve duty already in a real Task
  // Program is exactly a 7-hour duty (checked dozens of real rows across multiple days -- every
  // single one is sign-in to sign-out +7:00, never anything else). Used to give an engine-added
  // reserve task the same real sign-in/sign-out pair a well-formed real reserve row already has,
  // instead of leaving those cells blank on export.
  const RESERVE_DURATION_MIN = 420;

  // We don't want to leave a driver with no job -- for every driver Generate left unassigned,
  // proposes a brand-new reserve task {code, startMin, kind, destination, driver} to add to the
  // day, rather than a blank row the supervisor has to fill in by hand. Two rules, both confirmed
  // directly:
  // 1) A sign-in time never gets more than 4 reserve slots (R, RA, RB, RC, in that fixed order).
  // 2) New reserve slots go on sign-in times that ALREADY exist somewhere in the day's real Task
  //    Program (trip or reserve alike) -- never an invented time -- and only within the driver's
  //    OWN currently-locked shift, so a reserve duty always mirrors a genuine operational start
  //    time for that shift, never a random hour. A shift with no real sign-in time at all that
  //    day falls back to the shift's own configured start time.
  // "Fair" distribution: always fills whichever eligible time currently has the FEWEST reserve
  // slots first, never stacking new ones onto an already-busier time while a thinner one sits
  // open -- confirmed directly: "3 at 8am, 4 at 5am, 3 at 10am... seems fair" vs "5 at 8am, 1 at
  // 9am, 2 at 10am, 1 at 12pm... does not seem fair." A driver whose own shift has every real
  // time already at the 4-slot cap is reported back in `stillUnassigned` rather than silently
  // dropped or forced onto an invented time.
  function buildReserveTasksForUnassignedDrivers(day, unassignedDrivers, conditions, rotationState) {
    const timesByShift = conditions.shifts.map(() => new Set());
    day.tasks.forEach((t) => {
      if (t.startMin == null) return;
      const idx = classifyShiftForMinutes(conditions, t.startMin);
      if (idx != null) timesByShift[idx].add(t.startMin);
    });

    const reserveCountByTime = {};
    const usedSuffixesByTime = {};
    day.tasks.forEach((t) => {
      if (t.kind !== "reserve" || t.startMin == null) return;
      reserveCountByTime[t.startMin] = (reserveCountByTime[t.startMin] || 0) + 1;
      const m = /^\d{3,4}\/\d{0,2}([A-Za-z]{1,3})$/.exec(t.code);
      if (m) (usedSuffixesByTime[t.startMin] = usedSuffixesByTime[t.startMin] || new Set()).add(m[1].toUpperCase());
    });

    // Whether a driver who ends up here could ALSO have been placed into a real, still-open
    // reserve task from the original file (instead of always inventing a new one) was checked
    // directly, twice -- once via a hand-built engine test, once via 3000 randomized scenarios
    // through the real per-day pipeline -- and confirmed structurally impossible: this function
    // only ever sees a driver whose whole day already went through the normal per-task loop
    // (which tries every open task, reserves included, against the full live-eligible pool
    // before this ever runs). If that driver were own-shift/rest/rule-4 eligible for ANY
    // still-open reserve task, the normal loop would already have placed them there directly --
    // a task's candidate pool is checked once, and a non-empty pool is never left unfilled. So a
    // driver only ever reaches this function when no such real open slot exists for them, which
    // is exactly what "invent one instead" is for.
    const created = [];
    const stillUnassigned = [];

    unassignedDrivers.forEach((driver) => {
      const st = rotationState[driver.id];
      const ownIdx = st ? computeShiftIndexForDriver(st, conditions, day.date) : null;
      let candidateTimes = ownIdx != null ? Array.from(timesByShift[ownIdx]) : [];
      if (!candidateTimes.length && ownIdx != null) {
        const fallback = parseHHMM(conditions.shifts[ownIdx].start);
        if (fallback != null) candidateTimes = [fallback];
      }
      // An auto-created reserve task is a REAL duty, not a placeholder -- it must obey the exact
      // same continuity rules as anything else this engine assigns, never rest time and never a
      // backward jump in this driver's own real clock beyond the same-shift grace (see
      // withinSameShiftForwardLimit above). Confirmed as a real, live bug: this path used to pick
      // ANY real time already used elsewhere in the driver's own shift band that day, with no
      // rest-time check and no continuity check at all -- so an unassigned driver whose real clock
      // had been trending through the afternoon for a week could get auto-reserved at 05:00 the
      // very next day purely because 05:00 happened to be the thinnest slot, undoing everything
      // rules 2 and 4 otherwise guarantee. Confirmed directly: an auto-added reserve "should take
      // into consideration the day before... so it goes smooth with what has been generated the
      // days before." If every real time in the band fails this, same as everywhere else in this
      // engine, the driver is left unassigned rather than forced into a jarring jump.
      candidateTimes = candidateTimes.filter((t) => {
        if (st && st.lastDutyEndMin != null) {
          const gap = minutesBetween(st.lastDutyEndDateKey, st.lastDutyEndMin, day.dateKey, t);
          if (gap < conditions.restHours * 60) return false;
        }
        return !st || withinSameShiftForwardLimit(driver, st, day, t);
      });
      const eligible = candidateTimes.filter((t) => (reserveCountByTime[t] || 0) < MAX_RESERVE_SLOTS_PER_TIME);
      if (!eligible.length) { stillUnassigned.push(driver); return; }
      // Thinnest time first; ties broken chronologically for determinism.
      eligible.sort((a, b) => (reserveCountByTime[a] || 0) - (reserveCountByTime[b] || 0) || a - b);
      const chosenTime = eligible[0];
      const used = usedSuffixesByTime[chosenTime] || new Set();
      const suffix = RESERVE_SUFFIXES.find((s) => !used.has(s));
      if (!suffix) { stillUnassigned.push(driver); return; } // guarded by the count filter above, but stay safe
      const code = `${minutesToHHMM(chosenTime).replace(":", "")}/${RESERVE_ROUTE_DIGIT}${suffix}`;
      // Real Excel time cells wrap on a 24h clock, never carrying a next-day date even for a
      // reserve that actually crosses midnight (confirmed directly: a real 18:00 reserve's own
      // sign-out cell just reads 01:00, not "next day 1:00") -- % 1440 matches that convention.
      const endMin = (chosenTime + RESERVE_DURATION_MIN) % 1440;
      created.push({ code, startMin: chosenTime, endMin, kind: "reserve", destination: null, driver });
      reserveCountByTime[chosenTime] = (reserveCountByTime[chosenTime] || 0) + 1;
      (usedSuffixesByTime[chosenTime] = used).add(suffix);
    });

    return { created, stillUnassigned };
  }

  // Where each newly engine-added reserve task belongs on export -- confirmed directly: "place
  // each added reserve task to the timeslot... if there is a task at 3 AM, put it up there in the
  // 3 AM area" -- a real spreadsheet row landing at its actual chronological position among the
  // day's real rows, not always appended after the last one. Pure planning: this only decides
  // WHICH real row each new task belongs immediately before (grouping any that land in the same
  // gap together) -- XlsxSurgicalPatch.applyRowInsertions does the actual XML surgery once this
  // plan is hand to it. `day.tasks` is read here only for its REAL rows' own row/startMin (a
  // manual Add Task or an already-resolved original row still counts as "real" for this purpose --
  // anything with a genuine spreadsheet row); engineAddedReserve rows already in day.tasks from an
  // earlier Generate are excluded, since `addedReserveTasks` is the fresh list being planned now.
  // A new task whose time is at or after every real row's own time lands one past the last real
  // row (plain append, same as before) -- there's nothing real after it to land in front of.
  function planReserveRowInsertions(day, addedReserveTasks) {
    const realRows = day.tasks
      .filter((t) => !t.engineAddedReserve && t.row != null)
      .map((t) => ({ row: t.row, startMin: t.startMin != null ? t.startMin : Infinity }))
      .sort((a, b) => a.row - b.row);
    const lastRealRow = realRows.length ? realRows[realRows.length - 1].row : 0;

    const sorted = addedReserveTasks.slice().sort((a, b) => (a.startMin != null ? a.startMin : Infinity) - (b.startMin != null ? b.startMin : Infinity));
    const groups = [];
    sorted.forEach((task) => {
      const taskStart = task.startMin != null ? task.startMin : Infinity;
      const target = realRows.find((r) => r.startMin > taskStart);
      const beforeRow = target ? target.row : lastRealRow + 1;
      let group = groups.find((g) => g.beforeRow === beforeRow);
      if (!group) { group = { beforeRow, tasks: [] }; groups.push(group); }
      group.tasks.push(task);
    });
    groups.sort((a, b) => a.beforeRow - b.beforeRow);
    return groups;
  }

  // A driver's rotation-state update after being assigned one task -- extracted out of the
  // per-task loop in assignWithConditions so the exact same update can be replayed by
  // rebuildRotationStateFromSavedDays for a day's actual final (possibly hand-edited)
  // assignments, without needing assignWithConditions itself to have proposed them.
  function recordAssignment(state, day, task, driver, conditions) {
    const capLen = conditions.ratioReserveDays + conditions.ratioTripDays;
    const wantKind = task.kind === "reserve" ? "reserve" : "trip";
    const st = state[driver.id];
    const effectiveEndMin = task.endMin != null ? task.endMin : task.startMin;
    st.lastDutyEndDateKey = dutyEndDateKey(day, task.startMin, effectiveEndMin);
    st.lastDutyEndMin = effectiveEndMin;
    // The calendar day this duty was ASSIGNED for (not when it ends -- lastDutyEndDateKey can be
    // the next day for an overnight shift) plus its own start time, used only to smooth a
    // driver's real clock within their own current work stretch (see
    // withinSameShiftForwardLimit below) -- deliberately separate from lastDutyEndDateKey, which
    // exists for rest-time math and answers a different question.
    st.lastDutyDateKey = day.dateKey;
    st.lastDutyStartMin = task.startMin;
    st.recentKinds.push(wantKind);
    if (st.recentKinds.length > capLen) st.recentKinds.shift();
    if (wantKind === "reserve") st.cumulativeReserve = (st.cumulativeReserve || 0) + 1;
    else st.cumulativeTrip = (st.cumulativeTrip || 0) + 1;
    return wantKind;
  }

  // Shortest SIGNED delta (in minutes, `toMin` relative to `fromMin`) around a 1440-minute clock,
  // returned in (-720, 720]. Used only for the same-shift forward-smoothing check below --
  // correctly handles a shift whose own configured start wraps past midnight (Night) the same way
  // a same-day one does. Safe here because the window this feeds (a max 60min backward exception,
  // no forward cap at all) is always small relative to a half-day, so there's never a genuine
  // ambiguity about which direction is actually shorter.
  function signedMinuteDelta(fromMin, toMin) {
    let d = (toMin - fromMin) % 1440;
    if (d > 720) d -= 1440;
    if (d <= -720) d += 1440;
    return d;
  }

  // True if the driver was marked unavailable (a real day off) on ANY date strictly between their
  // last recorded real duty and the day being considered now -- meaning their current work
  // stretch has broken, so the same-shift forward-smoothing check below doesn't apply to this
  // first day back (nothing real to be smooth relative to across a genuine rest break). Also true
  // if there's no prior real duty recorded at all yet. Confirmed directly: "Resets after a day
  // off... each unbroken stretch of working days is its own sequence."
  function hadRealDayOffSince(driver, lastDutyDateKey, currentDateKey) {
    if (!lastDutyDateKey) return true;
    let d = addDays(new Date(lastDutyDateKey + "T00:00:00"), 1);
    const current = new Date(currentDateKey + "T00:00:00");
    while (d < current) {
      if (!isAvailable(driver.statusByDateKey[dateKey(d)])) return true;
      d = addDays(d, 1);
    }
    return false;
  }

  // A driver's real clock time within their OWN currently locked shift should trend forward
  // across an unbroken work stretch, never jump back more than a small grace amount. Confirmed
  // directly with a real 6-day example (03:00, 03:00, 03:30, 04:00, 05:00, 06:00 -- always equal
  // or later than the day before): "I don't want to see is if he start... at 6 AM, sending him
  // back to 3 AM. This is what I don't want to see, backward time shift." Backward is allowed only
  // as a bounded last resort -- "you're allowed to move him backward in hours, half an hour or an
  // hour, that's it, other than that leave it blank" -- so a step earlier than 60min back is
  // rejected outright, same "leave it unassigned rather than force it" shape as every other hard
  // rule here. Deliberately scoped to a driver's OWN shift only (see the per-task loop below) --
  // separate from, and unrelated to, the shift-index-only widening rule. (Rule 6, just below,
  // covers the forward direction -- no hard cap there, but a real preference for keeping it
  // gradual too.)
  const SAME_SHIFT_MAX_BACKWARD_MIN = 60;
  function withinSameShiftForwardLimit(driver, st, day, taskStartMin) {
    if (hadRealDayOffSince(driver, st.lastDutyDateKey, day.dateKey)) return true;
    if (st.lastDutyStartMin == null) return true;
    return signedMinuteDelta(st.lastDutyStartMin, taskStartMin) >= -SAME_SHIFT_MAX_BACKWARD_MIN;
  }

  // Rule 6: forward movement should also be SMOOTH within an unbroken work stretch, not just
  // legal -- confirmed directly against a real contrasting pair: a gradual 1h/1h/2h/1h day-to-day
  // climb ("something like that smooth and clean") vs. a single 5-hour jump in one day (12:00 ->
  // 17:00) singled out as exactly the pattern to avoid -- "sleep cycle cannot be affected." Unlike
  // the backward rule above, this is a soft PREFERENCE, not a hard block -- confirmed directly,
  // twice: "if you have to do this there's no other choice then you can do it," and confirmed
  // again when asked directly whether to make it a hard rule ("no"). So it's applied as a
  // pool-narrowing step in the per-task loop, never as a reason to leave a task unassigned the way
  // rest-time or the backward cap can. Confirmed to outrank the reserve/trip fairness ratio when
  // the two disagree ("smoothness wins first") -- narrows the pool before that ratio sort ever
  // runs, not just a tie-break within it.
  //
  // Graduated, not a single cutoff -- confirmed directly ("let's start with two hours, if he
  // cannot do that two hours let's give him a bigger window to three hour or 3 1/2 or four hours
  // as a max"): try the tightest window first, widen a step at a time only when that tier's pool
  // is genuinely empty, and only fall through to a truly unlimited jump if even the widest tier
  // (4h) has nobody. Each step is strictly wider than the last, so this is naturally ordered --
  // whichever tier a candidate satisfies, they also satisfy every tier after it.
  const SMOOTH_FORWARD_STEP_TIERS_MIN = [120, 180, 210, 240];
  function forwardStepMinutes(driver, st, day, taskStartMin) {
    if (hadRealDayOffSince(driver, st.lastDutyDateKey, day.dateKey) || st.lastDutyStartMin == null) return 0;
    const delta = signedMinuteDelta(st.lastDutyStartMin, taskStartMin);
    return delta > 0 ? delta : 0;
  }

  // v2: restores shift-locking (removed in the earlier whole-month rebuild once real start times
  // turned out not to cluster into clean bands) because v2's day-by-day human review closes the
  // gap that finding was actually about -- a supervisor now looks at every single day before it
  // counts, so the risk of a rigid lock producing an unreviewed mistake no longer applies the
  // same way, and the supervisor explicitly wants the familiar 2-week rotation back. A driver's
  // locked shift is the strong default: a task first tries only drivers locked into its own shift
  // for the whole shiftLockWeeks stretch (see computeShiftIndexForDriver -- advances exactly one
  // shift in the fixed chain per elapsed shiftLockWeeks period, compounding cleanly over multiple
  // periods; "the shift rotation should always meet the condition setting... if it's set to two
  // weeks then this driver's shift will be the same for two weeks then you can move him to the
  // next shift in a row... one shift up... from the safety department, the sleep cycle of the
  // driver [is what this protects]").
  //
  // If (and only if) nobody rested is left in a task's own shift, it may widen to EXACTLY the one
  // shift immediately before it in the fixed chain -- never further, never the shift after, no
  // minute-based distance math at all (an earlier design capped this by real clock-time distance
  // instead of shift identity; replaced after the shift bands themselves were narrowed to three
  // per period, since a fixed few-hour time cap could then reach a full two shifts forward under
  // the narrower bands, contradicting the actual rule). Confirmed directly: "you can borrow a
  // driver from his shift, but only from the next shift... if he's in early morning, you can put
  // him in morning, that's it. You cannot put him in late morning or early afternoon. You can go
  // one shift up only" -- and no backward case at all this time ("remove backward entirely").
  // shiftIdx 0 (Early Morning) has no shift before it to borrow from at all. If nobody in that one
  // prior shift is rested either, the task is left unassigned for the supervisor to fix by hand,
  // same as every other unfillable case -- no manufactured reserve duty, no jump too large just to
  // fill a gap. Fairness keeps the soft-nudge shape from the real-data rebuild (prefer whoever's
  // behind on ratio, prefer not repeating yesterday's kind) -- no hard quota was reintroduced.
  // A driver's real, already-fixed pre-existing duties (see resolveExistingTaskAssignments) are
  // ground truth this engine never rewrites -- but they're also evidence the engine should look
  // AHEAD at, not just behind. Without this, a driver whose own locked shift naturally rotates
  // forward (the ordinary 2-week shiftLockWeeks cycle, not even a borrow) can get freshly assigned
  // into a later shift on day N, one or two days before a real pre-existing entry already fixes
  // them back into an EARLIER shift on day M > N -- a visible backward drop the engine created by
  // assigning into a spot it had no way to know was about to be contradicted by already-real data.
  // Confirmed directly against a real file: a driver's own lock rotated Early Morning -> Late
  // Morning right on schedule, filled two ordinary Late-Morning tasks, and the very next day's
  // ALREADY-EXISTING answer (present in the file before this session ever opened it) put her back
  // in Early Morning -- the rotation model had no visibility into that fixed future at all.
  // Builds driverId -> chronologically-sorted list of every pre-existing duty's {dateKey, shiftIdx}
  // across `lookaheadDays` (the WHOLE loaded range, not just the day(s) being generated right now --
  // v1 already passes the whole month as its `taskDays`, so this is free there; v2's per-day
  // Generate passes its own separate lookahead range explicitly, see assignWithConditions below).
  function buildFutureFixedShiftIndex(lookaheadDays, conditions) {
    const byDriver = {};
    lookaheadDays.forEach((day) => {
      day.tasks.forEach((task) => {
        if (!task.originalDriverRawText || !task.driver) return;
        const idx = classifyShiftForMinutes(conditions, task.startMin);
        if (idx == null) return;
        (byDriver[task.driver.id] = byDriver[task.driver.id] || []).push({ dateKey: day.dateKey, shiftIdx: idx });
      });
    });
    Object.values(byDriver).forEach((list) => list.sort((a, b) => a.dateKey.localeCompare(b.dateKey)));
    return byDriver;
  }

  function assignWithConditions(rosterData, taskDays, conditions, rotationState, specialRules, shiftSeedAssignment, lookaheadTaskDays) {
    const state = rotationState || {};
    const rules = specialRules || [];
    const targetReserveFrac = conditions.ratioReserveDays / (conditions.ratioReserveDays + conditions.ratioTripDays);
    const cycleLen = conditions.shifts.length;
    // Defaults to `taskDays` itself -- v1's existing call (the whole month in one go) already IS
    // the full lookahead range, so this costs it nothing; only v2's day-by-day Generate needs to
    // pass its own wider range explicitly to see beyond the single day it's generating.
    const lookaheadDays = lookaheadTaskDays || taskDays;
    const futureFixedShiftByDriver = buildFutureFixedShiftIndex(lookaheadDays, conditions);
    const nextFixedShiftAfter = (driverId, afterDateKey) => {
      const list = futureFixedShiftByDriver[driverId];
      if (!list) return null;
      const hit = list.find((entry) => entry.dateKey > afterDateKey);
      return hit ? hit.shiftIdx : null;
    };

    const perDay = taskDays.map((day) => {
      const available = rosterData.drivers.filter((d) => isAvailable(d.statusByDateKey[day.dateKey]));

      // A driver with no rotation state at all yet (first time seen, this run or a previous one)
      // gets locked into a shift per shiftSeedAssignment -- precomputed once from the WHOLE
      // month's real task demand (see computeShiftSeedAssignment), not an even spread by position
      // in today's available list, so the cumulative mix of locked drivers actually matches how
      // the work is shaped. Falls back to the old even-spread-by-position behavior if no seed
      // assignment was supplied (keeps this an optional argument for any other caller). A driver
      // who already has state but no anchor (e.g. loaded from a memory file granted back when
      // shift-lock was removed) is anchored here too, instead of staying permanently unclassifiable.
      available.forEach((d, i) => {
        if (!state[d.id]) {
          state[d.id] = { shiftAnchorDate: null, shiftAnchorIndex: null, lastDutyEndDateKey: null, lastDutyEndMin: null, lastDutyDateKey: null, lastDutyStartMin: null, recentKinds: [], cumulativeReserve: 0, cumulativeTrip: 0 };
        }
        if (state[d.id].shiftAnchorDate == null) {
          state[d.id].shiftAnchorDate = day.dateKey;
          const seeded = shiftSeedAssignment && shiftSeedAssignment[d.id];
          state[d.id].shiftAnchorIndex = seeded != null ? seeded : i % cycleLen;
        }
      });

      const byShift = {};
      available.forEach((d) => {
        const idx = computeShiftIndexForDriver(state[d.id], conditions, day.date);
        (byShift[idx] = byShift[idx] || []).push(d);
      });

      const usedDriverIds = new Set();
      const assignments = [];
      const unassignedTasks = [];

      const restFilter = (list, task) => list.filter((d) => {
        if (isExcludedBySpecialRule(d, task, rules)) return false;
        const st = state[d.id];
        if (st.lastDutyEndMin != null) {
          const gap = minutesBetween(st.lastDutyEndDateKey, st.lastDutyEndMin, day.dateKey, task.startMin);
          if (gap < conditions.restHours * 60) return false;
        }
        // Don't hand this driver a fresh assignment today if a real, already-fixed pre-existing
        // duty on a later date would make it look like they got sent backward -- see
        // buildFutureFixedShiftIndex above. Same "skip rather than force it" philosophy as the
        // forward-borrow cap: if this is the only thing ruling every candidate out, the task is
        // left unassigned rather than manufacturing a jump we already know is coming.
        const taskShiftIdx = classifyShiftForMinutes(conditions, task.startMin);
        const nextFixed = taskShiftIdx != null ? nextFixedShiftAfter(d.id, day.dateKey) : null;
        if (nextFixed != null && nextFixed < taskShiftIdx) return false;
        return true;
      });

      // A task that already has a real answer -- either resolved from the original file's own
      // NAME cell (see resolveExistingTaskAssignments) or already given a driver by something
      // else this run -- is never reconsidered here. Without this, a real, already-answered task
      // from a partially-completed month would look identical to a genuinely open one and could
      // get silently reassigned to someone else entirely (a real, confirmed corruption risk when
      // the uploaded Task Program isn't a blank month).
      const workableTasks = day.tasks.filter((t) => !t.driver && !t.originalDriverRawText);

      // Policy: trip (and sweep) tasks are filled before reserve tasks whenever the day's
      // driver pool runs short -- "make priority to the trip tasks... a reserve task can have
      // no driver assigned... make sure the trip task always filled." Processing every
      // non-reserve task first, reserve tasks last, is what makes a scarce driver pool exhaust
      // itself on reserve tasks rather than on trips. Only the processing order changes here --
      // day.tasks itself (and its row/col patch targets) is untouched.
      const orderedTasks = workableTasks.filter((t) => t.kind !== "reserve").concat(spreadReserveTasks(workableTasks.filter((t) => t.kind === "reserve")));

      orderedTasks.forEach((task) => {
        const shiftIdx = classifyShiftForMinutes(conditions, task.startMin);
        const inShift = (byShift[shiftIdx] || []).filter((d) => !usedDriverIds.has(d.id));

        // Own locked shift tried first, rest-time never violated, AND -- within that same shift
        // -- never a backward step of more than SAME_SHIFT_MAX_BACKWARD_MIN from wherever this
        // driver's real clock last was in their current work stretch (see
        // withinSameShiftForwardLimit above).
        let pool = restFilter(inShift, task).filter((d) => withinSameShiftForwardLimit(d, state[d.id], day, task.startMin));

        // Only widen once the driver's own locked shift has nobody rested left in it -- to
        // EXACTLY the one shift immediately before this one in the fixed chain, never further,
        // never the shift after, never a minute-based distance check. shiftIdx 0 (Early Morning)
        // has no shift before it to borrow from at all.
        //
        // A real, confirmed bug lived here: this widened pool used to be filtered by restFilter
        // ONLY, omitting the same withinSameShiftForwardLimit check the own-shift pool above
        // already applies. The no-large-backward-jump rule is about a driver's real clock, not
        // about which shift band a task happens to be classified into -- so a driver borrowed
        // one-shift-up had zero backward-jump protection, and could be handed a task hours
        // earlier than their last real duty purely because they were reached via the widening
        // branch instead of their own shift. Traced from a real supervisor report of exactly this
        // (a driver's day2 task landing 3-4 hours earlier than day1's, no day off between).
        if (!pool.length && shiftIdx != null && shiftIdx > 0) {
          const priorShiftPool = (byShift[shiftIdx - 1] || []).filter((d) => !usedDriverIds.has(d.id));
          pool = restFilter(priorShiftPool, task).filter((d) => withinSameShiftForwardLimit(d, state[d.id], day, task.startMin));
        }

        // Early Morning (shiftIdx 0) has no shift before it in the chain, so it never had ANY
        // rescue at all until now -- confirmed as the real cause of a real supervisor's unfilled
        // 3-5:30am tasks: the seed boost above can only grow how many drivers get anchored there,
        // it can't do anything about a driver being off, in training, or on leave that specific
        // day, and the diagnosis showed the whole locked pool coming up empty on exactly that kind
        // of day. This exception borrows from Morning (shiftIdx 1) instead -- the one real,
        // available pool of drivers nearby -- under the EXACT same protections as every other
        // widen (rest time, and no jump further back than this driver's own real clock allows).
        // Confirmed directly against a real month: a rescue mechanism alone (no seed change) only
        // ever reached ~88% fill even with this exception, because roughly half the whole roster
        // is off on any given day regardless of which shift they're nominally locked to -- so this
        // is a genuine improvement, not a guarantee, and never overrides rest time or the
        // same-shift-forward-limit check to force one through.
        if (!pool.length && shiftIdx === 0) {
          const morningPool = (byShift[1] || []).filter((d) => !usedDriverIds.has(d.id));
          pool = restFilter(morningPool, task).filter((d) => withinSameShiftForwardLimit(d, state[d.id], day, task.startMin));
        }

        if (!pool.length) { unassignedTasks.push(task); return; }

        // Rule 6: narrow toward a smooth forward step BEFORE the kind-alternation/fairness
        // preferences below even get a look -- confirmed to outrank the reserve/trip ratio, not
        // just break a tie with it (see forwardStepMinutes/SMOOTH_FORWARD_STEP_TIERS_MIN above).
        // Tries the tightest tier first, widening a step at a time only when that tier's pool is
        // genuinely empty; falls back to the full pool (truly unlimited jump) only when even the
        // widest tier has nobody -- this is a preference, never a reason to leave the task
        // unassigned.
        let workingPool = pool;
        for (const tierMax of SMOOTH_FORWARD_STEP_TIERS_MIN) {
          const tierPool = pool.filter((d) => forwardStepMinutes(d, state[d.id], day, task.startMin) <= tierMax);
          if (tierPool.length) { workingPool = tierPool; break; }
        }

        const wantKind = task.kind === "reserve" ? "reserve" : "trip";

        // Priority cascade toward a real mix, not just an on-target ratio -- confirmed directly:
        // "reserve reserve reserve / trip trip trip" is NOT acceptable, but "if there is no other
        // choice than giving a driver three consecutive days as a reserve, we can do it... we will
        // not keep these drivers with no job." So this is a PREFERENCE ladder, not a hard rule:
        // 1) best -- full alternation, nobody repeats yesterday's kind (RTRTRT).
        // 2) fallback -- a single repeat is fine as long as it wouldn't be a THIRD in a row
        //    (RTRRTR) -- notRepeating is always a subset of this (repeating yesterday's kind is a
        //    precondition for a third-in-a-row, so anyone who avoided a repeat automatically
        //    avoided a streak too).
        // 3) fallback -- a 3rd in a row is fine as long as it wouldn't be a 4TH (RTRRRT) --
        //    notThirdConsecutive is always a subset of this for the same reason as above. This tier
        //    was missing entirely until a real audit found a driver hitting 6 consecutive reserve
        //    days -- "no 4 consecutive... soft preference with last-resort escape valve" means 4 is
        //    the escape valve, not an open door past 3.
        // 4) true last resort -- if literally every remaining candidate would already be a 4th (or
        //    deeper) consecutive same-kind duty, allow it anyway rather than leave the task
        //    unassigned, but prefer whoever's CURRENT streak is shortest (see the sort below) so
        //    the same driver doesn't keep absorbing every subsequent day's worth of this.
        const notRepeating = workingPool.filter((d) => !isRepeatingLastKind(state[d.id], wantKind));
        const notThirdConsecutive = workingPool.filter((d) => !wouldBeThirdConsecutiveKind(state[d.id], wantKind));
        const notFourthConsecutive = workingPool.filter((d) => !wouldBeFourthConsecutiveKind(state[d.id], wantKind));
        const isTrueLastResort = !notRepeating.length && !notThirdConsecutive.length && !notFourthConsecutive.length;
        const finalPool = notRepeating.length ? notRepeating
          : notThirdConsecutive.length ? notThirdConsecutive
          : notFourthConsecutive.length ? notFourthConsecutive
          : workingPool;

        // Soft nudge toward the configured ratio -- whoever's furthest behind on this kind
        // relative to their own history sorts first, but this never excludes anyone the way a
        // hard quota did. Ties break toward the SMALLEST forward step within a driver's own
        // current work stretch (0 for anyone exempt -- a fresh stretch, or a widened/first-ever
        // candidate) -- matches the gradual, minimal-creep shape rule 6 prefers, not just "forward
        // is legal, jump however far". In the true-last-resort tier, current streak length decides
        // FIRST, ahead of both -- every remaining candidate is already guaranteed to exceed the
        // preferred 3-in-a-row cap, so the priority shifts to minimizing how much further past it
        // this pick goes, not who's most behind on ratio.
        finalPool.sort((a, b) => {
          if (isTrueLastResort) {
            const streakDiff = currentStreakLength(state[a.id], wantKind) - currentStreakLength(state[b.id], wantKind);
            if (streakDiff !== 0) return streakDiff;
          }
          const scoreA = ratioPreference(state[a.id], targetReserveFrac, wantKind) + specialRuleBias(a, task, rules);
          const scoreB = ratioPreference(state[b.id], targetReserveFrac, wantKind) + specialRuleBias(b, task, rules);
          const ratioDiff = scoreB - scoreA;
          if (ratioDiff !== 0) return ratioDiff;
          return forwardStepMinutes(a, state[a.id], day, task.startMin) - forwardStepMinutes(b, state[b.id], day, task.startMin);
        });
        const chosen = finalPool[0];

        usedDriverIds.add(chosen.id);
        assignments.push({ task, driver: chosen, shiftIdx });
        recordAssignment(state, day, task, chosen, conditions);
      });

      // Rule 5: "never leave a trip task unassigned." Confirmed directly this stays best-effort,
      // not absolute -- own shift, then exactly one shift up (rule 2's scope, never further), rest
      // time never relaxed. A real, wanted addition here (bumping a driver THIS SAME Generate
      // already placed on a reserve duty onto a still-open trip) turned out to be provably
      // impossible to ever actually fire under those two limits: reserve tasks are always
      // processed after every trip using the identical eligibility test, so any driver who ends up
      // on a reserve duty was, by construction, not yet used when every trip was decided -- meaning
      // they'd already have been in that trip's own candidate pool if they were ever eligible for
      // it. A trip stays unassigned only when its pool was genuinely empty, and nobody becomes
      // newly eligible afterward (eligibility never changes; usedDriverIds only grows). So beyond
      // own-shift + one-shift-up widening, a trip that still can't be filled here genuinely can't
      // be, without either relaxing rest or re-solving multiple tasks' picks together -- both
      // explicitly out of scope for now (confirmed: "leave it as best-effort").

      return {
        date: day.date, dateKey: day.dateKey, sheetIndex: day.sheetIndex, nameCol: day.nameCol,
        assignments,
        unassignedTasks,
        // Any driver still available with nothing assigned -- deliberately left blank rather
        // than given a manufactured duty; buildPatches() only recolors these cells (the idle
        // flag), never writes a value, so a supervisor can spot and fill them in by hand.
        unassignedDrivers: available.filter((d) => !usedDriverIds.has(d.id)),
      };
    });
    return { perDay, rotationState: state };
  }

  // v2's day-by-day workflow means a day's result can be hand-edited, saved as a checkpoint,
  // later un-saved (edited) and re-saved -- so rotation state can't just be assignWithConditions's
  // mutated-in-place object, since that can't be "undone" when a day's save is undone. This
  // instead re-derives state from scratch by replaying every currently-saved day, in date order,
  // applying each day's ACTUAL FINAL assignments (post any supervisor hand-edits, read straight
  // off each task's live `.driver` field) via the same recordAssignment used by a live Generate.
  // Independent of whatever assignWithConditions originally proposed for a day -- only what's
  // saved now matters. `days` is the live taskDays-shaped array (each task carrying whatever
  // `.driver` the supervisor's edits left it with, or null if still unassigned). Note this is
  // distinct from Grant, a separate month-level action (see the v2 HTML) that finalizes whatever
  // is saved at that point as the month's schedule and carries it forward as next month's memory
  // -- this function only concerns itself with a single session's own day-to-day chain.
  //
  // Deliberately does NOT read the roster's own statusByDateKey to figure out who was "available"
  // that day, unlike a live Generate -- a live Generate itself writes each assignment's code back
  // into that exact same cell (see the "Roster grid" write-back in v2's own Generate handler), so
  // by the time a LATER day's replay runs, an earlier saved day's cells are no longer blank; a
  // driver actually assigned that day would misleadingly look "unavailable" in a fresh scan and
  // get skipped for first-seen shift-anchor seeding. A first-seen driver here is instead anchored
  // to the shift matching the task they were actually observed doing that day -- real information
  // this replay has and a live Generate's blind, position-based spread doesn't need to guess at.
  // A driver who was available but genuinely got nothing that day isn't seeded here at all; they
  // get seeded fresh, correctly, by the live Generate call itself when THEIR day comes up.
  // shiftSeedAssignment (optional but should always be passed by v2): the SAME whole-month,
  // demand-shaped seed a live Generate's own cold-start uses (see assignWithConditions, "gets
  // locked into a shift per shiftSeedAssignment... not an even spread"). Previously this replay
  // guessed a first-seen driver's locked shift from whatever task they actually happened to do
  // that day -- which silently adopted a CROSS-SHIFT BORROW as if it were their real locked
  // shift, the moment that borrow happened to be the first thing this replay ever saw for them.
  // From then on every later day's Generate treated the borrowed shift as their genuine baseline,
  // and the next time THAT shift ran short, borrowed them one more real step forward from the
  // wrong starting point -- each individual step still looked like "just one shift," but the
  // baseline itself crept across the whole week. Confirmed against real Sep1-8 data: drivers
  // ending up spread across three or four different shift bands in a single week, not the smooth
  // single-step transition intended. A live Generate never has this problem -- it seeds a driver's
  // anchor from shiftSeedAssignment the moment they're first AVAILABLE, before any task of theirs
  // is even considered, so a borrowed task can never retroactively redefine their baseline. This
  // now does the identical thing: a first-seen driver's anchor always comes from
  // shiftSeedAssignment when it's available, exactly matching what a live cold-start would have
  // given them, regardless of which task (real or engine-borrowed) this replay happens to see
  // first. Falls back to the observed task's own shift only if this driver has no seed entry at
  // all (defensive -- shiftSeedAssignment is built from the whole roster, so this shouldn't
  // normally happen).
  function rebuildRotationStateFromSavedDays(days, savedDateKeys, conditions, shiftSeedAssignment) {
    const state = {};
    const savedSet = new Set(savedDateKeys);
    const orderedDays = days
      .filter((day) => savedSet.has(day.dateKey))
      .slice()
      .sort((a, b) => (a.dateKey < b.dateKey ? -1 : a.dateKey > b.dateKey ? 1 : 0));

    orderedDays.forEach((day) => {
      (day.tasks || []).forEach((task) => {
        if (!task.driver) return;
        if (!state[task.driver.id]) {
          const seeded = shiftSeedAssignment && shiftSeedAssignment[task.driver.id];
          const shiftIdx = seeded != null ? seeded : classifyShiftForMinutes(conditions, task.startMin);
          state[task.driver.id] = { shiftAnchorDate: day.dateKey, shiftAnchorIndex: shiftIdx != null ? shiftIdx : 0, lastDutyEndDateKey: null, lastDutyEndMin: null, lastDutyDateKey: null, lastDutyStartMin: null, recentKinds: [], cumulativeReserve: 0, cumulativeTrip: 0 };
        }
        recordAssignment(state, day, task, task.driver, conditions);
      });
    });

    return state;
  }

  // Self-check, not a filter: by the time this runs, every assignment it looks at has already
  // happened (Generate, a hand-edit, whatever) -- it can only report a violation, never prevent
  // one. Built after a real, still-unexplained case where a supervisor's actual browser run
  // produced a driver bouncing between shift bands and a 9-hour backward jump within the same
  // shift, on files that (checked directly) had none of the known causes -- no pre-existing data,
  // no leftover cross-month memory, matching Conditions, a genuine day-by-day Generate+Save. That
  // left no way to tell, after the fact, which specific Generate call produced the bad assignment
  // or why. This exists so the NEXT time something like it happens, it's caught the moment it
  // happens, with the exact driver/date/rule, instead of being reconstructed days later from an
  // exported file with no trace back to its cause.
  //
  // Re-derives shift-lock and same-shift-forward eligibility using the exact same helpers the real
  // assignment loop uses (computeShiftIndexForDriver, withinSameShiftForwardLimit, recordAssignment)
  // -- not a separate reimplementation that could disagree with the real logic -- and checks every
  // task in `days` that has a driver and isn't a pre-existing real answer (originalDriverRawText),
  // in chronological order. `rotationState` supplies each driver's shift anchor (shiftAnchorDate/
  // shiftAnchorIndex) only; last-duty/streak bookkeeping is replayed fresh across just `days` so the
  // check is self-consistent regardless of what came before this range. A driver with no anchor at
  // all in `rotationState` is skipped for the shift-lock check (nothing to compare against) rather
  // than false-flagged.
  function auditRotationRules(days, conditions, rotationState) {
    const violations = [];
    const orderedDays = days.slice().sort((a, b) => (a.dateKey < b.dateKey ? -1 : a.dateKey > b.dateKey ? 1 : 0));
    const state = {};
    Object.keys(rotationState || {}).forEach((id) => {
      const src = rotationState[id];
      state[id] = {
        shiftAnchorDate: src.shiftAnchorDate || null, shiftAnchorIndex: src.shiftAnchorIndex != null ? src.shiftAnchorIndex : null,
        lastDutyEndDateKey: null, lastDutyEndMin: null, lastDutyDateKey: null, lastDutyStartMin: null,
        recentKinds: [], cumulativeReserve: 0, cumulativeTrip: 0,
      };
    });

    orderedDays.forEach((day) => {
      (day.tasks || []).forEach((task) => {
        if (!task.driver || task.originalDriverRawText) return;
        const driver = task.driver;
        if (!state[driver.id]) {
          state[driver.id] = { shiftAnchorDate: null, shiftAnchorIndex: null, lastDutyEndDateKey: null, lastDutyEndMin: null, lastDutyDateKey: null, lastDutyStartMin: null, recentKinds: [], cumulativeReserve: 0, cumulativeTrip: 0 };
        }
        const st = state[driver.id];
        const taskIdx = classifyShiftForMinutes(conditions, task.startMin);
        const lockIdx = computeShiftIndexForDriver(st, conditions, day.date);

        if (lockIdx != null && taskIdx != null && taskIdx !== lockIdx && taskIdx !== lockIdx + 1) {
          violations.push({
            driverId: driver.id, driverName: driver.name, dateKey: day.dateKey, rule: "shift-lock",
            detail: `assigned into "${conditions.shifts[taskIdx].name}" (${minutesToHHMM(task.startMin)}) while locked into "${conditions.shifts[lockIdx].name}" -- neither their own shift nor exactly one shift up`,
          });
          // A real, confirmed gap lived here: this branch (own shift OR the one legitimate
          // one-shift-up borrow) used to only run the backward-jump check when taskIdx === lockIdx
          // exactly -- so a driver correctly borrowed one shift up was never checked for a
          // backward-clock jump at all, the same omission assignWithConditions's own widened pool
          // had (see the comment there). This audit exists specifically to catch the live
          // assignment loop's mistakes after the fact, so it needs the identical two-case coverage
          // that loop's own filtering now has, not just the own-shift half of it.
        } else if (lockIdx != null && taskIdx != null && !withinSameShiftForwardLimit(driver, st, day, task.startMin)) {
          violations.push({
            driverId: driver.id, driverName: driver.name, dateKey: day.dateKey, rule: "same-shift-forward",
            detail: `start time ${minutesToHHMM(task.startMin)} (${taskIdx === lockIdx ? "own shift" : "one-shift-up borrow"}) is more than ${SAME_SHIFT_MAX_BACKWARD_MIN}min earlier than their last duty (${minutesToHHMM(st.lastDutyStartMin)} on ${st.lastDutyDateKey}), with no real day off in between`,
          });
        }

        // This audit never checked consecutive-kind streaks at all, despite existing specifically
        // to catch the live loop's mistakes after the fact -- the same missing coverage the live
        // loop itself had before wouldBeFourthConsecutiveKind was added (see there). Uses the same
        // reserve-vs-not-reserve bucketing recordAssignment always has (a sweep counts as "trip"
        // for this purpose, matching live behavior).
        const wantKindForStreak = task.kind === "reserve" ? "reserve" : "trip";
        if (wouldBeFourthConsecutiveKind(st, wantKindForStreak)) {
          violations.push({
            driverId: driver.id, driverName: driver.name, dateKey: day.dateKey, rule: "consecutive-kind",
            detail: `assigned a ${wantKindForStreak} that would be their 4th+ consecutive ${wantKindForStreak} in a row (recent history: ${(st.recentKinds || []).join(",") || "none"})`,
          });
        }
        recordAssignment(state, day, task, driver, conditions);
      });
    });

    return violations;
  }

  // Per-driver, per-week breakdown of shift + trip/reserve/sweep counts for a generated run --
  // the reference the supervisor asked for so a following month's Generate can be run with an
  // eye on fairness (whoever got more trips this run can deliberately get more reserve next
  // time). Weeks are plain 7-day blocks starting from the first day actually processed, labeled
  // with real dates rather than trying to replicate calendar week boundaries.
  function buildMonthlySummary(plan, conditions, rotationState) {
    const days = plan.perDay;
    if (!days.length) return { weeks: [], driverSummaries: [] };

    const weeks = [];
    for (let i = 0; i < days.length; i += 7) {
      const chunk = days.slice(i, i + 7);
      weeks.push({ index: weeks.length, startDateKey: chunk[0].dateKey, endDateKey: chunk[chunk.length - 1].dateKey, days: chunk });
    }

    const byDriver = {};
    function ensure(driver) {
      if (!byDriver[driver.id]) {
        byDriver[driver.id] = {
          driver,
          weeks: weeks.map(() => ({ shiftIndexes: new Set(), tripCount: 0, reserveCount: 0, sweepCount: 0 })),
        };
      }
      return byDriver[driver.id];
    }

    weeks.forEach((week, wi) => {
      week.days.forEach((day) => {
        day.assignments.forEach(({ task, driver }) => {
          const wk = ensure(driver).weeks[wi];
          if (task.kind === "reserve") wk.reserveCount++;
          else if (task.kind === "sweep") wk.sweepCount++;
          else wk.tripCount++;
          // Which shift this driver was actually locked into that week -- back to reading the
          // lock itself now that shift-lock is restored, rather than each assignment's own start
          // time.
          const st = rotationState[driver.id];
          const shiftIdx = st ? computeShiftIndexForDriver(st, conditions, day.date) : null;
          if (shiftIdx != null) wk.shiftIndexes.add(shiftIdx);
        });
      });
    });

    const driverSummaries = Object.values(byDriver)
      .map((rec) => ({
        driverId: rec.driver.id,
        name: rec.driver.name,
        totalTrips: rec.weeks.reduce((s, w) => s + w.tripCount, 0),
        totalReserve: rec.weeks.reduce((s, w) => s + w.reserveCount, 0),
        totalSweep: rec.weeks.reduce((s, w) => s + w.sweepCount, 0),
        weeks: rec.weeks.map((wk) => ({
          shiftNames: [...wk.shiftIndexes].map((i) => conditions.shifts[i].name),
          tripCount: wk.tripCount,
          reserveCount: wk.reserveCount,
          sweepCount: wk.sweepCount,
        })),
      }))
      .sort((a, b) => a.name.localeCompare(b.name));

    return {
      weeks: weeks.map((w) => ({ index: w.index, startDateKey: w.startDateKey, endDateKey: w.endDateKey })),
      driverSummaries,
    };
  }

  // --- Rotation memory: portable, explicit save/restore of rotationState --------------------
  // Automatically persisting rotationState in the browser (what an earlier version of this tool
  // did) turned out to be dangerous: it silently carried leftover state from testing/experiments
  // into real runs, with no visibility into what was even stored -- confirmed to cause massive,
  // hard-to-diagnose unassigned-task counts (a driver's memorized "last duty end" landing AFTER
  // the new run's start date makes the rest-time gap compute negative, instantly failing that
  // driver out of every task, for almost the entire roster at once).
  // The fix is making memory an explicit, portable file a supervisor grants on purpose (see the
  // "Grant" flow in the HTML) instead of something that accumulates invisibly. These two
  // functions are the pure data half of that: turning rotationState into plain rows a caller can
  // write into a worksheet, and reading those rows back out of an uploaded workbook.

  function minutesToHHMM(min) {
    const h = Math.floor(min / 60), m = min % 60;
    return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}`;
  }

  // Excel stores a time-of-day as a fraction of a 24h day (09:00 -> 0.375) in a numeric cell,
  // paired with a time number format on the cell's style to display it as HH:MM -- see
  // buildCellXml in xlsx_surgical_patch.js for why this has to be a real number, not text.
  function minutesToExcelTimeSerial(min) {
    return min / 1440;
  }

  function monthKeyFromDateKey(dk) {
    return dk.slice(0, 7);
  }

  function monthLabelFromDateKey(dk) {
    const d = new Date(dk + "T00:00:00");
    return d.toLocaleDateString("en-US", { month: "long", year: "numeric" });
  }

  function buildMemoryRows(rosterData, rotationState) {
    const nameById = {};
    rosterData.drivers.forEach((d) => { nameById[d.id] = d.name; });
    return Object.keys(rotationState).map((id) => {
      const st = rotationState[id];
      return {
        driverId: id,
        driverName: nameById[id] || "",
        shiftAnchorDate: st.shiftAnchorDate || null,
        shiftAnchorIndex: st.shiftAnchorIndex != null ? st.shiftAnchorIndex : null,
        lastDutyEndDateKey: st.lastDutyEndDateKey || null,
        lastDutyEndTime: st.lastDutyEndMin != null ? minutesToHHMM(st.lastDutyEndMin) : null,
        recentKinds: (st.recentKinds || []).join(","),
        cumulativeReserve: st.cumulativeReserve || 0,
        cumulativeTrip: st.cumulativeTrip || 0,
      };
    });
  }

  // Reads a memory workbook back into { station, monthLabel, grantedAt, rotationState } --
  // by label, not by fixed row/column numbers, the same way parseRoster/parseTaskProgram locate
  // their own headers, so this isn't brittle against exactly how a caller laid out the metadata
  // rows above the table.
  function parseMemoryWorkbook(workbook) {
    const ws = workbook.worksheets[0];
    if (!ws) throw new Error("This memory file has no worksheet.");

    const idHeaderCell = findHeaderCell(ws, "Driver ID", 20);
    if (!idHeaderCell) throw new Error("This doesn't look like a rotation memory file -- no \"Driver ID\" column found. Was it downloaded from this tool's Grant button?");
    const lastEndDateCell = findHeaderCell(ws, "Last Duty End Date", 20);
    const lastEndTimeCell = findHeaderCell(ws, "Last Duty End Time", 20);
    const recentKindsCell = findHeaderCell(ws, "Recent Kinds", 20);
    if (!lastEndDateCell || !lastEndTimeCell || !recentKindsCell) {
      throw new Error("This memory file is missing one or more expected columns -- was it downloaded from this tool's Grant button?");
    }
    // Added later than the other columns -- optional so an older memory file (granted before
    // cumulative fairness tracking existed, or during the stretch when shift-lock was removed)
    // still loads, just starting cumulative counts at 0 / with no shift anchor rather than
    // failing to load altogether. A missing anchor gets re-seeded from scratch on that driver's
    // next Generate (see assignWithConditions), rather than leaving them unclassifiable forever.
    const cumReserveCell = findHeaderCell(ws, "Cumulative Reserve", 20);
    const cumTripCell = findHeaderCell(ws, "Cumulative Trip", 20);
    const anchorDateCell = findHeaderCell(ws, "Shift Anchor Date", 20);
    const anchorIdxCell = findHeaderCell(ws, "Shift Anchor Index", 20);

    const readAdjacent = (cell) => {
      if (!cell) return null;
      const v = displayValue(ws.getRow(cell.row).getCell(cell.col + 1));
      if (v == null || v === "") return null;
      return v instanceof Date ? v.toISOString() : String(v).trim();
    };
    const station = readAdjacent(findHeaderCell(ws, "Station", 10));
    const monthLabel = readAdjacent(findHeaderCell(ws, "Granted for", 10));
    const grantedAt = readAdjacent(findHeaderCell(ws, "Granted at", 10));

    const headerRow = idHeaderCell.row;
    const idCol = idHeaderCell.col;
    const rotationState = {};
    for (let r = headerRow + 1; r <= ws.rowCount; r++) {
      const row = ws.getRow(r);
      const idVal = displayValue(row.getCell(idCol));
      if (idVal == null || String(idVal).trim() === "") continue;
      const id = String(idVal).trim();
      const lastEndDateVal = displayValue(row.getCell(lastEndDateCell.col));
      const lastEndTimeVal = displayValue(row.getCell(lastEndTimeCell.col));
      const recentKindsVal = displayValue(row.getCell(recentKindsCell.col));
      const cumReserveVal = cumReserveCell ? displayValue(row.getCell(cumReserveCell.col)) : null;
      const cumTripVal = cumTripCell ? displayValue(row.getCell(cumTripCell.col)) : null;
      const anchorDateVal = anchorDateCell ? displayValue(row.getCell(anchorDateCell.col)) : null;
      const anchorIdxVal = anchorIdxCell ? displayValue(row.getCell(anchorIdxCell.col)) : null;
      rotationState[id] = {
        shiftAnchorDate: anchorDateVal != null && anchorDateVal !== "" ? String(anchorDateVal).trim() : null,
        shiftAnchorIndex: anchorIdxVal != null && anchorIdxVal !== "" ? parseInt(anchorIdxVal, 10) : null,
        lastDutyEndDateKey: lastEndDateVal != null && lastEndDateVal !== "" ? String(lastEndDateVal).trim() : null,
        lastDutyEndMin: lastEndTimeVal != null && lastEndTimeVal !== "" ? parseHHMM(String(lastEndTimeVal).trim()) : null,
        recentKinds: recentKindsVal != null && recentKindsVal !== "" ? String(recentKindsVal).split(",").map((s) => s.trim()).filter(Boolean) : [],
        cumulativeReserve: cumReserveVal != null && cumReserveVal !== "" ? parseInt(cumReserveVal, 10) : 0,
        cumulativeTrip: cumTripVal != null && cumTripVal !== "" ? parseInt(cumTripVal, 10) : 0,
      };
    }
    if (!Object.keys(rotationState).length) throw new Error("This memory file has no driver rows in it.");

    return { station, monthLabel, grantedAt, rotationState };
  }

  // Converts a plan into plain {row, col, value} patch lists, grouped by sheet index, ready for
  // xlsx_surgical_patch.js's applyCellPatches() -- deliberately NOT an ExcelJS workbook mutation.
  // Earlier versions of this engine wrote assignments directly into a live ExcelJS workbook and
  // asked ExcelJS to serialize the whole file back out, which turned out to be provably lossy in
  // ways that corrupted real output files (dropped external-link formulas left dangling, and a
  // ~460KB drawing part rebuilt as a ~1KB stub that made the file unopenable in real Excel).
  // Producing plain patch data here, with no ExcelJS involvement in the write path at all, is
  // what lets the surgical patcher touch only the exact cells being changed and nothing else.
  // "flag": true patch entries are style-only (no value change) -- xlsx_surgical_patch.js applies
  // a distinct fill color to those cells and leaves their content exactly as-is, marking a driver
  // who was available that day but genuinely had no task left to assign them (every task that
  // day was already filled) so a supervisor can see it at a glance rather than the cell just
  // looking like an ordinary blank/available day.
  // Matches the Task Program's own NAME-column convention when a VLOOKUP resolves successfully
  // (confirmed directly against a real file's resolved output): "<prefix, e.g. 'T- '><ID>-<NAME>"
  // followed immediately by the phone number, no separator -- whatever format the roster's own
  // Phone column happens to have it in.
  function formatDriverForTaskCell(driver) {
    return `${driver.namePrefix || ""}${driver.id}-${driver.name}${driver.phone || ""}`;
  }

  function buildPatches(plan) {
    const rosterPatches = { 0: [] };
    const taskPatches = {};
    plan.perDay.forEach((day) => {
      if (!taskPatches[day.sheetIndex]) taskPatches[day.sheetIndex] = [];
      day.assignments.forEach(({ task, driver, shiftIdx }) => {
        taskPatches[day.sheetIndex].push({ row: task.row, col: day.nameCol, value: formatDriverForTaskCell(driver) });
        // shiftIdx colors the roster cell so a supervisor can see each day's shift at a glance --
        // one color per shift (see SHIFT_FLAG_ARGB_CANDIDATES in xlsx_surgical_patch.js), picked
        // per-file to avoid colliding with that file's own existing palette. The value written is
        // the real roster's own stripped format (see stripCodeForRoster), not the Task Program's
        // full letter-suffixed code.
        rosterPatches[0].push({ row: driver.row, col: driver.colByDateKey[day.dateKey], value: stripCodeForRoster(task.code), shiftIdx });
      });
      // A driver left genuinely unassigned (nothing safe to give them) gets only a color flag --
      // the cell's content is left exactly as it was (blank), for a supervisor to fill in by hand.
      (day.unassignedDrivers || []).forEach((driver) => {
        rosterPatches[0].push({ row: driver.row, col: driver.colByDateKey[day.dateKey], flag: true });
      });
    });
    return { rosterPatches, taskPatches };
  }

  return {
    dateKey, addDays, isAvailable, classifyCode, classifyDestination, stripCodeForRoster,
    parseRoster, parseTaskProgram, assignSimple, buildPatches,
    SHIFT_NAMES, defaultConditions, parseHHMM, conditionsAreComplete,
    classifyShiftForMinutes, computeShiftIndexForDriver, assignWithConditions,
    computeShiftDemand, computeOpenShiftDemand, computeShiftSeedAssignment, buildFutureFixedShiftIndex,
    buildReserveTasksForUnassignedDrivers, findNextFreeTaskRow, planReserveRowInsertions,
    chainRescueSparePool, buildChainRescueMoves,
    readResolvedCell, parseResolvedNameCell, resolveExistingTaskAssignments,
    isOfficeDutyCode, syncOfficeDutyToRoster,
    recordAssignment, rebuildRotationStateFromSavedDays, auditRotationRules,
    buildMonthlySummary,
    minutesToHHMM, minutesToExcelTimeSerial, monthKeyFromDateKey, monthLabelFromDateKey,
    buildMemoryRows, parseMemoryWorkbook, formatDriverForTaskCell, spreadReserveTasks,
    isRepeatingLastKind,
  };
});
